#!/bin/sh
# Copies the forked Go template packages (tpl/internal/go_templates, which
# are internal to github.com/neohugo/neohugo/tpl and so cannot be imported
# from tools/) into ./fork with rewritten import paths, so the oracle can
# use the exact code neohugo executes. ./fork is gitignored; the oracle's
# own files carry the build tag `gotemplate_oracle` so that `go build ./...`
# and `go vet ./...` on a fresh checkout never see the missing package.
#
# Usage (from the repository root or this directory):
#   tools/go-oracle/gotemplate/sync-fork.sh
#   GOTOOLCHAIN=go1.27.1 go run -tags gotemplate_oracle ./tools/go-oracle/gotemplate <mode> ...
set -eu
here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../../.." && pwd)
src="$root/tpl/internal/go_templates"
dst="$here/fork"
rm -rf "$dst"
for pkg in texttemplate texttemplate/parse htmltemplate fmtsort; do
	mkdir -p "$dst/$pkg"
	for f in "$src/$pkg"/*.go; do
		case "$f" in *_test.go) continue ;; esac
		{
			echo "//go:build gotemplate_oracle"
			echo
			echo "// Code generated by sync-fork.sh from tpl/internal/go_templates. DO NOT EDIT."
			echo
			sed -e 's#github.com/neohugo/neohugo/tpl/internal/go_templates/#github.com/neohugo/neohugo/tools/go-oracle/gotemplate/fork/#g' "$f"
		} > "$dst/$pkg/$(basename "$f")"
	done
done
# Export a few unexported helpers the oracle needs (escaper funcs, stripTags,
# isJSType ...) through an extra file in the copied package.
cat > "$dst/htmltemplate/oracle_exports.go" <<'GO'
//go:build gotemplate_oracle

// Code generated by sync-fork.sh. DO NOT EDIT.

package template

// EscFuncs exposes the escaper func map (funcMap) to the oracle.
func EscFuncs() map[string]any { return funcMap }

// StripTagsExported exposes stripTags.
func StripTagsExported(s string) string { return stripTags(s) }

// IsJSTypeExported exposes isJSType.
func IsJSTypeExported(s string) bool { return isJSType(s) }

// --- html/template leaf functions (escfuncs mode) ---

// OracleCtx is a context with exported fields. Braces is the jsBraceDepth
// slice itself (not a copy), so slice aliasing stays observable.
type OracleCtx struct {
	State, Delim, URLPart, JSCtx, Attr, Element uint8
	Braces                                      []int
	Err                                         string
}

func toCtx(o OracleCtx) context {
	return context{
		state:        state(o.State),
		delim:        delim(o.Delim),
		urlPart:      urlPart(o.URLPart),
		jsCtx:        jsCtx(o.JSCtx),
		jsBraceDepth: o.Braces,
		attr:         attr(o.Attr),
		element:      element(o.Element),
	}
}

func fromCtx(c context) OracleCtx {
	o := OracleCtx{
		State: uint8(c.state), Delim: uint8(c.delim), URLPart: uint8(c.urlPart),
		JSCtx: uint8(c.jsCtx), Attr: uint8(c.attr), Element: uint8(c.element),
		Braces: c.jsBraceDepth,
	}
	if c.err != nil {
		o.Err = c.err.Error()
	}
	return o
}

// TransitionStepExported runs transitionFunc[c.state] once.
func TransitionStepExported(o OracleCtx, s []byte) (OracleCtx, int) {
	c := toCtx(o)
	c2, n := transitionFunc[c.state](c, s)
	return fromCtx(c2), n
}

// ContextStringExported exposes context.String (without an error).
func ContextStringExported(o OracleCtx) string { return toCtx(o).String() }

// MangleExported exposes context.mangle.
func MangleExported(o OracleCtx, name string) string { return toCtx(o).mangle(name) }

// NextJSCtxExported exposes nextJSCtx.
func NextJSCtxExported(s []byte, preceding uint8) uint8 {
	return uint8(nextJSCtx(s, jsCtx(preceding)))
}

// AttrTypeExported exposes attrType.
func AttrTypeExported(name string) uint8 { return uint8(attrType(name)) }

// IndexTagEndExported exposes indexTagEnd.
func IndexTagEndExported(s, tag []byte) int { return indexTagEnd(s, tag) }

// DecodeCSSExported exposes decodeCSS.
func DecodeCSSExported(s []byte) []byte { return decodeCSS(s) }

// EndsWithCSSKeywordExported exposes endsWithCSSKeyword.
func EndsWithCSSKeywordExported(b []byte, kw string) bool { return endsWithCSSKeyword(b, kw) }

// IsSafeURLExported exposes isSafeURL.
func IsSafeURLExported(s string) bool { return isSafeURL(s) }

// ContainsSpecialScriptTagExported exposes containsSpecialScriptTag.
func ContainsSpecialScriptTagExported(s []byte) bool { return containsSpecialScriptTag(s) }

// EscapeSpecialScriptTagsExported exposes escapeSpecialScriptTags.
func EscapeSpecialScriptTagsExported(s []byte) []byte { return escapeSpecialScriptTags(s) }

// ScriptTagReplaceExported applies jsValEscaper's scriptTagRe rewrite.
func ScriptTagReplaceExported(s []byte) []byte {
	return scriptTagRe.ReplaceAll(s, []byte(`\x3C${1}script`))
}
GO
cat > "$dst/htmltemplate/oracle_exports_escdump.go" <<'GO'
//go:build gotemplate_oracle

// Code generated by sync-fork.sh. DO NOT EDIT.

package template

import texttemplate "github.com/neohugo/neohugo/tools/go-oracle/gotemplate/fork/texttemplate"

// TextTemplate exposes the underlying text/template of an html template.
func (t *Template) TextTemplate() *texttemplate.Template { return t.text }
GO
cat > "$dst/htmltemplate/oracle_exports_htmlexec.go" <<'GO'
//go:build gotemplate_oracle

// Code generated by sync-fork.sh. DO NOT EDIT.

package template

import (
	texttemplate "github.com/neohugo/neohugo/tools/go-oracle/gotemplate/fork/texttemplate"
	"github.com/neohugo/neohugo/tools/go-oracle/gotemplate/fork/texttemplate/parse"
)

// EscapeTextExported runs escapeText over one text node from the start
// context (TestEscapeText) and returns the output context and whether the
// node text was left unmodified.
func EscapeTextExported(text string) (string, bool) {
	b, e := []byte(text), makeEscaper(nil)
	c := e.escapeText(context{}, &parse.TextNode{NodeType: parse.NodeText, Text: b})
	return c.String(), string(b) == text
}

// EnsurePipelineContainsExported runs ensurePipelineContains on the first
// action of src (TestEnsurePipelineContains) and returns the pipeline.
func EnsurePipelineContainsExported(src string, ids []string) (string, error) {
	tmpl, err := texttemplate.New("test").Parse(src)
	if err != nil {
		return "", err
	}
	action, ok := tmpl.Tree.Root.Nodes[0].(*parse.ActionNode)
	if !ok {
		return "", nil
	}
	ensurePipelineContains(action.Pipe, append([]string(nil), ids...))
	return action.Pipe.String(), nil
}

// RedundantFuncsExported lists the redundantFuncs pairs.
func RedundantFuncsExported() map[string]map[string]bool { return redundantFuncs }
GO
echo "fork copied to $dst"
