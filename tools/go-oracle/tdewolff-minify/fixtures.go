// scale multiplies the number of generated random cases.
var scale = 1

// fixWriter writes one gzip-compressed, tab-separated fixture file.
type fixWriter struct {
	f  *os.File
	gz *gzip.Writer
	bw *bufio.Writer
	n  int
}

func newFix(dir, name string) *fixWriter {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		panic(err)
	}
	f, err := os.Create(filepath.Join(dir, name+".txt.gz"))
	if err != nil {
		panic(err)
	}
	gz, _ := gzip.NewWriterLevel(f, gzip.BestCompression)
	gz.ModTime = gz.ModTime.UTC() // zero time: reproducible output
	bw := bufio.NewWriter(gz)
	_, _ = fmt.Fprintf(bw, "# generated by tools/go-oracle/tdewolff-minify fixtures (%s); DO NOT EDIT\n", goVersion())
	return &fixWriter{f, gz, bw, 0}
}

func (w *fixWriter) rec(fields ...string) {
	_, _ = w.bw.WriteString(strings.Join(fields, "\t"))
	_ = w.bw.WriteByte('\n')
	w.n++
}

func (w *fixWriter) close() {
	if err := w.bw.Flush(); err != nil {
		panic(err)
	}
	if err := w.gz.Close(); err != nil {
		panic(err)
	}
	if err := w.f.Close(); err != nil {
		panic(err)
	}
	fmt.Fprintf(os.Stderr, "%s: %d records\n", w.f.Name(), w.n)
}

func hx(b []byte) string { return hex.EncodeToString(b) }

func errStr(err error) string {
	if err == nil {
		return "-"
	}
	return hx([]byte(err.Error()))
}

// cp is append([]byte(nil), s...) (Go size-class capacity).
func cp(s []byte) []byte { return append([]byte(nil), s...) }

// runM minifies a private copy of in through m.Minify and returns the
// output, the (possibly rewritten in place) input copy and the error.
func runM(m *minify.M, mediatype string, in []byte) ([]byte, []byte, error) {
	buf := cp(in)
	var w bytes.Buffer
	err := m.Minify(mediatype, &w, buffer.NewReader(buf))
	return w.Bytes(), buf, err
}

// sameOr returns "=" when b equals ref, else hex(b).
func sameOr(b, ref []byte) string {
	if bytes.Equal(b, ref) {
		return "="
	}
	return hx(b)
}

// minRec writes `min CONFIG MEDIATYPE INPUT OUTPUT ERR AFTER`.
func minRec(w *fixWriter, cfg string, m *minify.M, mediatype string, in []byte) {
	out, after, err := runM(m, mediatype, in)
	w.rec("min", cfg, hx([]byte(mediatype)), hx(in), sameOr(out, in), errStr(err), sameOr(after, in))
}

// testLiterals returns every string literal inside a Test* function of the
// _test.go files of the given minify package (sorted, deduplicated).
func testLiterals(pkg string) [][]byte {
	dir := filepath.Join(minifyModuleDir(), pkg)
	fset := token.NewFileSet()
	matches, err := filepath.Glob(filepath.Join(dir, "*_test.go"))
	if err != nil {
		panic(err)
	}
	seen := map[string]bool{}
	var lits []string
	for _, fn := range matches {
		f, err := parser.ParseFile(fset, fn, nil, 0)
		if err != nil {
			panic(err)
		}
		for _, decl := range f.Decls {
			fd, ok := decl.(*ast.FuncDecl)
			if !ok || !strings.HasPrefix(fd.Name.Name, "Test") {
				continue
			}
			ast.Inspect(fd, func(n ast.Node) bool {
				if bl, ok := n.(*ast.BasicLit); ok && bl.Kind == token.STRING {
					s, err := strconv.Unquote(bl.Value)
					if err == nil && !seen[s] {
						seen[s] = true
						lits = append(lits, s)
					}
				}
				return true
			})
		}
	}
	sort.Strings(lits)
	out := make([][]byte, len(lits))
	for i, s := range lits {
		out[i] = []byte(s)
	}
	return out
}

