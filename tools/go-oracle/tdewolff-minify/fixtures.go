func genFixtures(dir string) {
	// upstream tables
	w := newFix(dir, "upstream")
	genUpstream(w)
	w.close()

	// every upstream test literal through the relevant configs
	w = newFix(dir, "literals")
	for _, k := range kinds {
		lits := testLiterals(k.pkg)
		for _, cfg := range k.configs {
			m := configByName(cfg)
			for _, mt := range k.mediatypes {
				for _, in := range lits {
					minRec(w, cfg, m, mt, in)
				}
			}
		}
	}
	w.close()

	// random mutations
	w = newFix(dir, "fuzz")
	genFuzzRecords(w, 1500*scale, 1)
	w.close()

	// grammar-shaped css / svg path / html
	w = newFix(dir, "structured")
	genStructured(w, 1500*scale, 3)
	w.close()

	// unit functions
	w = newFix(dir, "units")
	genUnits(w)
	w.close()
}

// seedsFor returns the fuzz seeds of a kind: upstream literals plus
// snippets of the site corpora when available (SEEKSNACK_GOLDEN, CORPUS2).
func seedsFor(k kind) [][]byte {
	seeds := testLiterals(k.pkg)
	add := func(root string, exts ...string) {
		if root == "" {
			return
		}
		var files []string
		_ = filepath.Walk(root, func(p string, info os.FileInfo, err error) error {
			if err != nil || info.IsDir() {
				return nil
			}
			for _, e := range exts {
				if strings.HasSuffix(p, e) {
					files = append(files, p)
				}
			}
			return nil
		})
		sort.Strings(files)
		// take up to 40 files spread over the corpus
		step := 1
		if len(files) > 40 {
			step = len(files) / 40
		}
		for i := 0; i < len(files); i += step {
			b, err := os.ReadFile(files[i])
			if err == nil && len(b) > 0 {
				seeds = append(seeds, b)
			}
		}
	}
	g := os.Getenv("SEEKSNACK_GOLDEN")
	c2 := os.Getenv("CORPUS2")
	switch k.name {
	case "html":
		add(g, ".html")
	case "xml":
		add(g, ".xml")
	case "css":
		if c2 != "" {
			add(filepath.Join(c2, "css"), ".in")
			add(filepath.Join(c2, "css-resource"), ".in")
		}
	case "svg":
		if c2 != "" {
			add(filepath.Join(c2, "svg"), ".in")
		}
	case "json":
		if c2 != "" {
			add(filepath.Join(c2, "json"), ".in")
		}
	}
	return seeds
}

// mutate returns a random mutation of one or two seeds (at most 700 bytes).
func mutate(r *rand.Rand, seeds [][]byte, dict []string) []byte {
	window := func(b []byte, max int) []byte {
		if len(b) <= max {
			return cp(b)
		}
		n := 1 + r.Intn(max)
		i := r.Intn(len(b) - n + 1)
		return cp(b[i : i+n])
	}
	b := window(seeds[r.Intn(len(seeds))], 400)
	ops := 1 + r.Intn(5)
	for k := 0; k < ops; k++ {
		pos := 0
		if len(b) > 0 {
			pos = r.Intn(len(b) + 1)
		}
		switch r.Intn(8) {
		case 0, 1, 2: // insert dictionary token
			t := dict[r.Intn(len(dict))]
			b = append(b[:pos], append([]byte(t), b[pos:]...)...)
		case 3: // delete a range
			if len(b) > 0 {
				n := 1 + r.Intn(8)
				if pos+n > len(b) {
					n = len(b) - pos
				}
				b = append(b[:pos], b[pos+n:]...)
			}
		case 4: // splice another seed window
			o := window(seeds[r.Intn(len(seeds))], 80)
			b = append(b[:pos], append(o, b[pos:]...)...)
		case 5: // replace a byte
			if pos < len(b) {
				const special = " \t\n\r\f\"'<>=&;:,./\\#%+-!?*()[]{}0123456789eE"
				b[pos] = special[r.Intn(len(special))]
			}
		case 6: // duplicate a range
			if len(b) > 0 {
				i := r.Intn(len(b))
				n := 1 + r.Intn(16)
				if i+n > len(b) {
					n = len(b) - i
				}
				d := cp(b[i : i+n])
				b = append(b[:pos], append(d, b[pos:]...)...)
			}
		case 7: // insert a random byte (NUL, high bytes included)
			c := byte(r.Intn(256))
			b = append(b[:pos], append([]byte{c}, b[pos:]...)...)
		}
	}
	if len(b) > 700 {
		b = b[:700]
	}
	return b
}

// genFuzzRecords writes n random cases per kind, each through every config
// and mediatype of the kind (cycled).
func genFuzzRecords(w *fixWriter, n int, seed int64) {
	r := rand.New(rand.NewSource(seed))
	for _, k := range kinds {
		seeds := seedsFor(k)
		ms := make([]*minify.M, len(k.configs))
		for i, c := range k.configs {
			ms[i] = configByName(c)
		}
		for i := 0; i < n; i++ {
			in := mutate(r, seeds, k.dict)
			ci := i % len(k.configs)
			mt := k.mediatypes[(i/len(k.configs))%len(k.mediatypes)]
			minRec(w, k.configs[ci], ms[ci], mt, in)
			if k.configs[ci] != "seeksnack" && i%3 == 0 {
				minRec(w, "seeksnack", configByName("seeksnack"), k.mediatypes[0], in)
			}
		}
	}
}

// fuzzGen writes a large random differential set (fuzz.txt.gz) to OUTDIR.
func fuzzGen(outDir string, n int, seed int64, _ []string) {
	w := newFix(outDir, "fuzz")
	genFuzzRecords(w, n, seed)
	w.close()
}

var numberPrecs = []int{-1, 0, 1, 2, 3, 6, 15}
var decimalPrecs = []int{-1, 0, 1, 2, 3}

// genUnits writes records for the byte-level helpers:
//
//	num PREC IN OUT AFTER / dec PREC IN OUT AFTER / mt IN OUT AFTER /
//	duri CONFIG IN OUT AFTER / path PREC IN OUT AFTER
func genUnits(w *fixWriter) {
	r := rand.New(rand.NewSource(7))
	// numbers
	var nums [][]byte
	nums = append(nums, testLiterals("")...)
	if p := os.Getenv("NUMBERS_JSONL"); p != "" {
		f, err := os.Open(p)
		if err == nil {
			sc := bufio.NewScanner(f)
			sc.Buffer(make([]byte, 1<<20), 1<<20)
			for sc.Scan() {
				var rec map[string]any
				if stdjson.Unmarshal(sc.Bytes(), &rec) == nil {
					nums = append(nums, []byte(rec["in"].(string)))
				}
			}
			_ = f.Close()
		}
	}
	numDict := []string{"0", "1", "5", "9", ".", "e", "E", "-", "+", "00", "99", "e-", "e+", "000000000", "999999999", "123456789", "1e308", "5e-324", "9223372036854775807", "-9223372036854775808"}
	numSeeds := append([][]byte{}, nums...)
	for i := 0; i < 3000*scale; i++ {
		nums = append(nums, mutate(r, numSeeds, numDict))
	}
	for _, in := range nums {
		if len(in) > 120 {
			continue
		}
		for _, p := range numberPrecs {
			buf := cp(in)
			out := minify.Number(buf, p)
			w.rec("num", strconv.Itoa(p), hx(in), sameOr(out, in), sameOr(buf, in))
		}
		for _, p := range decimalPrecs {
			buf := cp(in)
			out := minify.Decimal(buf, p)
			w.rec("dec", strconv.Itoa(p), hx(in), sameOr(out, in), sameOr(buf, in))
		}
	}

	// mediatypes
	mts := testLiterals("")
	mtDict := []string{" ", "\t", "\n", "\"", ";", "=", "text/HTML", "Charset=UTF-8", "\"A B\"", "x", "/", ","}
	mtSeeds := append([][]byte{}, mts...)
	for i := 0; i < 800*scale; i++ {
		mts = append(mts, mutate(r, mtSeeds, mtDict))
	}
	for _, in := range mts {
		buf := cp(in)
		out := minify.Mediatype(buf)
		w.rec("mt", hx(in), sameOr(out, in), sameOr(buf, in))
	}

	// data URIs
	duris := testLiterals("")
	duriDict := []string{"data:", "data:text/plain;charset=us-ascii,", "data:image/svg+xml;charset=utf-8,", "data:;base64,", ";base64,", "%3Csvg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 16 16'%3E%3Cpath d='M0 0L1 1'/%3E%3C/svg%3E", "%20", "%", "+", ",", ";", "text/x,", "<?xx?>", "dGV4dA==", "IyMjIyMj", "&#43;", "\"", "#", " "}
	duriSeeds := append([][]byte{}, duris...)
	for i := 0; i < 800*scale; i++ {
		duris = append(duris, mutate(r, duriSeeds, duriDict))
	}
	for _, cfg := range []string{"seeksnack", "t-datauri", "default"} {
		m := configByName(cfg)
		for _, in := range duris {
			buf := cp(in)
			out := minify.DataURI(m, buf)
			w.rec("duri", cfg, hx(in), sameOr(out, in), sameOr(buf, in))
		}
	}

	// path data (fresh PathData per input, newPrecision unset as in upstream tests)
	paths := testLiterals("svg")
	pathDict := []string{"M", "m", "L", "l", "H", "h", "V", "v", "C", "c", "S", "s", "Q", "q", "T", "t", "A", "a", "Z", "z", " ", ",", "-", ".", "0", "1", "10", "100", ".5", "1e2", "1.5e-3", "0 0", "1 0 1", "4.646 1.646", "-.708"}
	pathSeeds := append([][]byte{}, paths...)
	for i := 0; i < 1500*scale; i++ {
		paths = append(paths, mutate(r, pathSeeds, pathDict))
	}
	for _, prec := range []int{0, 1, 3} {
		for _, in := range paths {
			p := svg.NewPathData(&svg.Minifier{Precision: prec})
			buf := cp(in)
			out := p.ShortenPathData(buf)
			w.rec("path", strconv.Itoa(prec), hx(in), sameOr(out, in), sameOr(buf, in))
		}
	}
}

