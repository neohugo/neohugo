func readAssets(root string) map[string][]string {
	out := map[string][]string{}
	add := func(kind, pattern string) {
		files, err := filepath.Glob(filepath.Join(root, pattern))
		if err != nil {
			log.Fatal(err)
		}
		sort.Strings(files)
		for _, fn := range files {
			b, err := os.ReadFile(fn)
			if err != nil {
				log.Fatal(err)
			}
			if len(b) > 64*1024 {
				continue
			}
			out[kind] = append(out[kind], string(b))
		}
	}
	add("css", "docs/assets/css/*.css")
	add("css", "docs/assets/css/components/*.css")
	add("js", "docs/assets/js/*.js")
	add("js", "docs/assets/js/*/*.js")
	add("json", "docs/assets/jsconfig.json")
	add("svg", "docs/assets/images/sponsors/*.svg")
	return out
}

// queried is the media types asked of the client per input kind (their
// Transformer and Minify), including types that only the regexps match and
// types without a minifier.
var queried = map[string][]string{
	"css":  {"text/css", "text/x-custom-css", "text/plain"},
	"js":   {"text/javascript", "application/javascript", "text/x-javascript", "application/ecmascript", "text/jscript"},
	"json": {"application/json", "application/ld+json", "application/manifest+json", "text/x-json", "text/json", "application/geo+json"},
	"svg":  {"image/svg+xml", "image/svg"},
	"xml":  {"application/xml", "application/rss+xml", "text/xml", "application/x-custom+xml", "application/atom+xml"},
	"html": {"text/html", "text/html; charset=utf-8", "text/x-custom-html", "application/xhtml+xml", "text/calendar"},
}

// extraTypes are added to media.DefaultTypes (suffixes decide the
// registration of the css/js/json/svg/xml/html minifiers).
var extraTypes = []struct {
	typ  string
	exts []string
}{
	{"text/x-custom-css", []string{"css"}},
	{"application/x-custom+xml", []string{"xml"}},
	{"text/x-custom-html", []string{"xhtml"}},
}

// fromTo is a transform.FromTo over two buffers (the chain's fromToBuffer).
type fromTo struct {
	from *bytes.Buffer
	to   *bytes.Buffer
}

func (ft fromTo) From() transform.BytesReader { return ft.from }
func (ft fromTo) To() io.Writer               { return ft.to }

func main() {
	root := flag.String("root", ".", "neohugo module root")
	out := flag.String("out", "crates/nh-transform/tests/fixtures/minify", "output directory")
	flag.Parse()

	if !osupport.IsChild() {
		patches := []osupport.Patch{osupport.MinifiersPatch}
		if err := osupport.RunOverlaid(*root, "./tools/go-oracle/nh-transform/minify", patches,
			"hook_overlay.go", hookFile, []string{"-root", *root, "-out", *out}); err != nil {
			log.Fatal(err)
		}
		return
	}
	if setConf == nil {
		log.Fatal("minify: hooks not installed (not run through the overlay)")
	}

	w, err := osupport.Create(filepath.Join(*out, "minify.jsonl.gz"))
	if err != nil {
		log.Fatal(err)
	}
	write := func(rec map[string]any) {
		if err := w.Write(rec); err != nil {
			log.Fatal(err)
		}
	}

	for _, c := range decodeCases {
		conf, err := minifiers.DecodeConfig(c)
		rec := map[string]any{"t": "decode", "in": enc(c)}
		if err != nil {
			rec["err"] = err.Error()
		} else {
			rec["conf"] = dumpConf(conf)
		}
		write(rec)
	}

	types := append(media.Types{}, media.DefaultTypes...)
	var extra []any
	for _, e := range extraTypes {
		t, err := media.FromStringAndExt(e.typ, e.exts...)
		if err != nil {
			log.Fatal(err)
		}
		types = append(types, t)
		extra = append(extra, map[string]any{"type": e.typ, "exts": e.exts})
	}
	formats := append(output.Formats{}, output.DefaultFormats...)
	customHTML, _ := types.GetByType("text/x-custom-html")
	formats = append(formats, output.Format{Name: "customhtml", MediaType: customHTML, IsHTML: true})

	variants := []struct {
		name string
		conf any
	}{
		{"default", m{"minifyoutput": true}},
		{"custom", customConf},
		{"disabled", m{"minifyoutput": true, "disablecss": true, "disablejs": true, "disablejson": true, "disablesvg": true, "disablexml": true, "disablehtml": true}},
		{"nooutput", nil},
	}

	inputs := readAssets(*root)
	for k, v := range snippets {
		inputs[k] = append(inputs[k], v...)
	}
	kinds := []string{"css", "js", "json", "svg", "xml", "html"}

	for _, v := range variants {
		conf, err := minifiers.DecodeConfig(v.conf)
		if err != nil {
			log.Fatal(err)
		}
		setConf(conf)
		client, err := minifiers.New(types, formats, nil)
		if err != nil {
			log.Fatal(err)
		}
		write(map[string]any{"t": "client", "variant": v.name, "conf": enc(v.conf), "extraTypes": extra, "minifyOutput": client.MinifyOutput})
		for _, kind := range kinds {
			for _, mt := range queried[kind] {
				for _, in := range inputs[kind] {
					rec := map[string]any{"t": "min", "variant": v.name, "mt": mt, "in": osupport.S(in)}
					tr := client.Transformer(media.Type{Type: mt})
					if tr == nil {
						rec["nil"] = true
					} else {
						var b bytes.Buffer
						var terr error
						// Called directly (Chain.Apply would wrap an error with a random
						// temp file name).
						pm := osupport.PanicString(func() { terr = tr(fromTo{from: bytes.NewBufferString(in), to: &b}) })
						switch {
						case pm != "":
							rec["trPanic"] = pm
						case terr != nil:
							rec["trErr"] = terr.Error()
						default:
							rec["tr"] = osupport.B(b.Bytes())
						}
					}
					var b bytes.Buffer
					var merr error
					pm := osupport.PanicString(func() { merr = client.Minify(media.Type{Type: mt}, &b, strings.NewReader(in)) })
					switch {
					case pm != "":
						rec["minPanic"] = pm
					case merr != nil:
						rec["minErr"] = merr.Error()
					default:
						rec["min"] = osupport.B(b.Bytes())
					}
					write(rec)
				}
			}
		}
	}

	if err := w.Close(); err != nil {
		log.Fatal(err)
	}
	log.Printf("minify: %d records (%s)", w.N(), osupport.Arch())
}
