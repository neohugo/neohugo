// Command minify is the Go oracle for minifiers/{config,minifiers}.go in
// crates/nh-transform (Wave B task T07): DecodeConfig and the minifier client
// (which media types get which tdewolff minifier with which options, the
// publish-chain Transformer and Client.Minify).
//
//	NH_T07_ORACLE_ARCH=arm64 go run ./tools/go-oracle/nh-transform/minify [-out crates/nh-transform/tests/fixtures/minify]
//
// The oracle runs itself again with `go build -overlay` (osupport.MinifiersPatch
// lets minifiers.New take the minify section from minifiers.OracleConf). The
// CSS/SVG colour conversions are FMA-sensitive (crates/tdewolff-minify
// PORTING.md), so the fixtures are generated by the linux/arm64 build under
// qemu (NH_T07_ORACLE_ARCH=arm64), like the golden darwin/arm64 build.
//
// Records (minify.jsonl.gz):
//
//   - "decode": DecodeConfig of typed config maps (lower-case keys as the
//     config loader delivers them, camelCase keys, the decimal/precision and
//     keepConditionalComments renames, map[string]string and maps.Params
//     nesting, weak conversions, bad values) → the decoded MinifyConfig or the
//     error;
//   - "min": for each config (default, customised, disabled types) and each
//     queried media type × input: whether Client.Transformer is nil, the
//     transformer's output (the publish chain) and Client.Minify's output, or
//     their errors. Inputs are the docs site's CSS/JS/SVG/JSON assets and
//     hand-written snippets per media type.
