// Command go-html is the Go oracle for the Rust crate crates/go-html.
//
// It has two jobs:
//
//	go run ./tools/go-oracle/go-html -entities crates/go-html/src/entity.rs
//	    generates the Rust entity table from $GOROOT/src/html/entity.go
//	    (parsed with go/parser, cross-checked against html.UnescapeString).
//	go run ./tools/go-oracle/go-html -fixtures crates/go-html/tests/fixtures/unescape.txt [-n N] [-seed S]
//	    writes differential fixtures: one line per input,
//	    "<input>\t<EscapeString>\t<UnescapeString>", each field encoded with esc().
//	go run ./tools/go-oracle/go-html -fixtures crates/go-html/tests/fixtures/adversarial.txt -adv N [-seed S]
//	    writes the adversarial cases of adversarial.go instead.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/ast"
	"go/constant"
	"go/parser"
	"go/token"
	"html"
	"log"
	"math/rand/v2"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"sort"
	"strconv"
	"strings"
)

type ent1 struct {
	name string
	r    rune
}

type ent2 struct {
	name string
	r    [2]rune
}

func main() {
	entities := flag.String("entities", "", "write the Rust entity table to this file")
	fixtures := flag.String("fixtures", "", "write the differential fixture to this file")
	n := flag.Int("n", 8000, "number of random inputs")
	seed := flag.Uint64("seed", 1, "random seed")
	inputs := flag.String("inputs", "", "optional file of extra inputs, one per line (e.g. lines of the golden site)")
	onlyInputs := flag.Bool("only-inputs", false, "emit only the cases for -inputs")
	adv := flag.Int("adv", 0, "with -fixtures: emit only the adversarial cases of adversarial.go (N random soups)")
	every := flag.Int("every", 1, "keep only every Nth case")
	flag.Parse()

	e1, e2 := loadEntities()
	if *entities != "" {
		writeEntities(*entities, e1, e2)
	}
	if *fixtures != "" {
		writeFixtures(*fixtures, e1, e2, *n, *seed, *inputs, *onlyInputs, *adv, *every)
	}
}

func goroot() string {
	out, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		log.Fatal(err)
	}
	return strings.TrimSpace(string(out))
}

// loadEntities parses $GOROOT/src/html/entity.go and evaluates the two map
// literals. Commented-out entries are skipped by the parser, exactly as the
// compiler does.
func loadEntities() ([]ent1, []ent2) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, filepath.Join(goroot(), "src", "html", "entity.go"), nil, 0)
	if err != nil {
		log.Fatal(err)
	}
	var e1 []ent1
	var e2 []ent2
	ast.Inspect(f, func(n ast.Node) bool {
		cl, ok := n.(*ast.CompositeLit)
		if !ok {
			return true
		}
		mt, ok := cl.Type.(*ast.MapType)
		if !ok {
			return true
		}
		switch vt := mt.Value.(type) {
		case *ast.Ident: // map[string]rune
			if vt.Name != "rune" {
				log.Fatalf("unexpected map value type %s", vt.Name)
			}
			for _, el := range cl.Elts {
				kv := el.(*ast.KeyValueExpr)
				e1 = append(e1, ent1{lit(kv.Key), runeLit(kv.Value)})
			}
			return false
		case *ast.ArrayType: // map[string][2]rune
			for _, el := range cl.Elts {
				kv := el.(*ast.KeyValueExpr)
				pair := kv.Value.(*ast.CompositeLit)
				if len(pair.Elts) != 2 {
					log.Fatal("entity2 value is not a pair")
				}
				e2 = append(e2, ent2{lit(kv.Key), [2]rune{runeLit(pair.Elts[0]), runeLit(pair.Elts[1])}})
			}
			return false
		}
		return true
	})
	sort.Slice(e1, func(i, j int) bool { return e1[i].name < e1[j].name })
	sort.Slice(e2, func(i, j int) bool { return e2[i].name < e2[j].name })

	// Cross-check against the real implementation.
	for _, e := range e1 {
		if got := html.UnescapeString("&" + e.name); got != string(e.r) {
			log.Fatalf("entity %q: parsed %q, html.UnescapeString gives %q", e.name, string(e.r), got)
		}
	}
	for _, e := range e2 {
		if got := html.UnescapeString("&" + e.name); got != string(e.r[0])+string(e.r[1]) {
			log.Fatalf("entity2 %q: parsed %q, html.UnescapeString gives %q", e.name, string(e.r[:]), got)
		}
	}
	if len(e1) < 2000 || len(e2) < 80 {
		log.Fatalf("suspiciously few entities: %d %d", len(e1), len(e2))
	}
	return e1, e2
}

func lit(e ast.Expr) string {
	bl := e.(*ast.BasicLit)
	s, err := strconv.Unquote(bl.Value)
	if err != nil {
		log.Fatal(err)
	}
	return s
}

func runeLit(e ast.Expr) rune {
	bl := e.(*ast.BasicLit)
	if bl.Kind != token.CHAR {
		log.Fatalf("not a rune literal: %s", bl.Value)
	}
	v, ok := constant.Int64Val(constant.MakeFromLiteral(bl.Value, token.CHAR, 0))
	if !ok {
		log.Fatal("bad rune literal")
	}
	return rune(v)
}

func writeEntities(path string, e1 []ent1, e2 []ent2) {
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/go-oracle/go-html -entities from go%s src/html/entity.go; DO NOT EDIT.\n\n", strings.TrimPrefix(runtime.Version(), "go"))
	b.WriteString("//! HTML entity tables (Go `html.entityMaps`), sorted by name for binary search.\n\n")
	fmt.Fprintf(&b, "/// Go `entity`: HTML entity name -> rune (%d entries).\n", len(e1))
	fmt.Fprintf(&b, "pub(crate) static ENTITY: [(&[u8], i32); %d] = [\n", len(e1))
	for _, e := range e1 {
		fmt.Fprintf(&b, "    (b%s, 0x%X),\n", strconv.Quote(e.name), e.r)
	}
	b.WriteString("];\n\n")
	fmt.Fprintf(&b, "/// Go `entity2`: HTML entity name -> two runes (%d entries).\n", len(e2))
	fmt.Fprintf(&b, "pub(crate) static ENTITY2: [(&[u8], [i32; 2]); %d] = [\n", len(e2))
	for _, e := range e2 {
		fmt.Fprintf(&b, "    (b%s, [0x%X, 0x%X]),\n", strconv.Quote(e.name), e.r[0], e.r[1])
	}
	b.WriteString("];\n")
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
}

// esc encodes arbitrary bytes into a single line: printable ASCII except
// backslash is kept, everything else is \xHH.
func esc(s string) string {
	var b strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c >= 0x20 && c < 0x7f && c != '\\' {
			b.WriteByte(c)
		} else {
			fmt.Fprintf(&b, "\\x%02x", c)
		}
	}
	return b.String()
}

// testLiterals returns every string literal of $GOROOT/src/html/*_test.go.
func testLiterals() []string {
	var out []string
	files, _ := filepath.Glob(filepath.Join(goroot(), "src", "html", "*_test.go"))
	for _, fn := range files {
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, fn, nil, 0)
		if err != nil {
			log.Fatal(err)
		}
		ast.Inspect(f, func(n ast.Node) bool {
			if bl, ok := n.(*ast.BasicLit); ok && bl.Kind == token.STRING {
				if s, err := strconv.Unquote(bl.Value); err == nil {
					out = append(out, s)
				}
			}
			return true
		})
	}
	return out
}

func writeFixtures(path string, e1 []ent1, e2 []ent2, n int, seed uint64, extra string, onlyExtra bool, adv, every int) {
	rng := rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15))
	var inputs []string
	add := func(s string) { inputs = append(inputs, s) }

	if adv > 0 {
		inputs = adversarialInputs(e1, e2, adv, rng)
	} else if !onlyExtra {
		inputs = append(inputs, testLiterals()...)

		// Every entity name in several contexts.
		for _, e := range e1 {
			nm := e.name
			add("&" + nm)
			add("x&" + nm + "y")
			add("&" + nm + "=")
			add("&" + nm + "&" + nm)
			if strings.HasSuffix(nm, ";") {
				base := nm[:len(nm)-1]
				add("&" + base)
				add("&" + base + "z;")
				add("&" + base + "Z")
				add("&" + strings.ToUpper(base) + ";")
			}
		}
		for _, e := range e2 {
			add("&" + e.name)
			add("a&" + e.name + "b")
			add("&" + strings.TrimSuffix(e.name, ";"))
		}
		// Numeric references.
		for c := 0; c < 0x140; c++ {
			add(fmt.Sprintf("&#%d;", c))
			add(fmt.Sprintf("&#x%x;", c))
			add(fmt.Sprintf("&#X%X", c))
			add(fmt.Sprintf("&#%d", c))
		}
		for _, v := range []int64{0xD7FF, 0xD800, 0xDBFF, 0xDC00, 0xDFFF, 0xE000, 0xFFFD, 0xFFFE, 0xFFFF,
			0x10000, 0x10FFFF, 0x110000, 0x7FFFFFFF, 0x80000000, 0xFFFFFFFF, 0x100000000, 0x1_0000_0041,
			1<<40 + 65, 99999999999999999} {
			add(fmt.Sprintf("&#%d;", v))
			add(fmt.Sprintf("&#x%x;", v))
			add(fmt.Sprintf("&#X%X-", v))
			add(fmt.Sprintf("&#%dz", v))
		}
		for _, s := range []string{"", "&", "&&", "&#", "&#;", "&#x", "&#x;", "&#X;", "&#a", "&#1", "&#1a", "&#12",
			"&#xg", "&#x1g", "&;", "&a;", "&ab", "&amp", "&amp;", "&AMP", "&amp;amp;", "&ampx", "&amp=",
			"&notin", "&notit;", "&noti", "&not", "&no", "&n", "&nGt;", "&nLt;", "&nGtv;", "a&", "&\xff",
			"&amp\xff", "&#\xff", "&#x\xff", "<>&'\"", "\x00&#0;", "&#00000000000000065;"} {
			add(s)
		}

		// Random soup.
		alphabet := []string{"&", "&", "&", "#", ";", "x", "X", "0", "1", "9", "a", "f", "A", "F", "g",
			"amp", "lt", "gt", "quot", "not", "in", "copy", "Aacute", "nGt", "gesl", "=", " ", "<", ">", "'", "\"",
			"\xff", "\xc3\xa9", "\xe2\x82\xac", "\xf0\x9f\x98\x80", "\x00", "\n", "8", "0x", "128"}
		for i := 0; i < n; i++ {
			k := rng.IntN(12)
			var b strings.Builder
			for j := 0; j < k; j++ {
				switch rng.IntN(10) {
				case 0:
					b.WriteString("&#")
					if rng.IntN(2) == 0 {
						b.WriteByte("xX"[rng.IntN(2)])
						for d := rng.IntN(10); d > 0; d-- {
							b.WriteByte("0123456789abcdefABCDEF"[rng.IntN(22)])
						}
					} else {
						for d := rng.IntN(12); d > 0; d-- {
							b.WriteByte("0123456789"[rng.IntN(10)])
						}
					}
					if rng.IntN(2) == 0 {
						b.WriteByte(';')
					}
				case 1:
					e := e1[rng.IntN(len(e1))].name
					b.WriteByte('&')
					b.WriteString(e[:1+rng.IntN(len(e))])
				default:
					b.WriteString(alphabet[rng.IntN(len(alphabet))])
				}
			}
			add(b.String())
		}
	}

	if extra != "" {
		data, err := os.ReadFile(extra)
		if err != nil {
			log.Fatal(err)
		}
		inputs = append(inputs, strings.Split(string(data), "\n")...)
	}

	if every > 1 {
		var kept []string
		for i, s := range inputs {
			if i%every == 0 {
				kept = append(kept, s)
			}
		}
		inputs = kept
	}

	f, err := os.Create(path)
	if err != nil {
		log.Fatal(err)
	}
	w := bufio.NewWriter(f)
	for _, s := range inputs {
		_, _ = fmt.Fprintf(w, "%s\t%s\t%s\n", esc(s), esc(html.EscapeString(s)), esc(html.UnescapeString(s)))
	}
	if err := w.Flush(); err != nil {
		log.Fatal(err)
	}
	if err := f.Close(); err != nil {
		log.Fatal(err)
	}
	fmt.Fprintf(os.Stderr, "wrote %d cases to %s\n", len(inputs), path)
}
