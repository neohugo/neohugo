type fixtureWriter struct {
	f *os.File
	w *bufio.Writer
	n int
}

func newFixture(dir, name string) *fixtureWriter {
	f, err := os.Create(filepath.Join(dir, name))
	if err != nil {
		panic(err)
	}
	fw := &fixtureWriter{f: f, w: bufio.NewWriter(f)}
	_, _ = fmt.Fprintf(fw.w, "# generated by tools/go-oracle/tdewolff-parse fixtures (%s); DO NOT EDIT\n", goVersion())
	return fw
}

// line writes one tab-separated record.
func (fw *fixtureWriter) line(fields ...string) {
	_, _ = fw.w.WriteString(strings.Join(fields, "\t"))
	_ = fw.w.WriteByte('\n')
	fw.n++
}

func (fw *fixtureWriter) close() {
	if err := fw.w.Flush(); err != nil {
		panic(err)
	}
	if err := fw.f.Close(); err != nil {
		panic(err)
	}
	fmt.Fprintf(os.Stderr, "%s: %d records\n", filepath.Base(fw.f.Name()), fw.n)
}

func itoa(i int) string      { return stdstrconv.Itoa(i) }
func i64(i int64) string     { return stdstrconv.FormatInt(i, 10) }
func u64s(u uint64) string   { return stdstrconv.FormatUint(u, 10) }
func fbits(f float64) string { return fmt.Sprintf("%016x", math.Float64bits(f)) }
func bstr(b bool) string {
	if b {
		return "1"
	}
	return "0"
}

// fuzz builds n pseudo-random inputs by splicing fragments together and
// sprinkling special bytes (deterministic for a given seed).
func fuzz(seed int64, n int, frags []string, extra []string) [][]byte {
	r := rand.New(rand.NewSource(seed))
	all := append(append([]string{}, frags...), extra...)
	specials := []byte{0, '\t', '\n', '\r', '\f', ' ', '<', '>', '/', '"', '\'', '=', '&', ';', '#', '-', '!', '?', '\\', '(', ')', '{', '}', '[', ']', ',', ':', '.', '*', 'e', 'E', '+', '%', 0x80, 0xC3, 0xA9, 0xE2, 0xF0, 0xFF}
	out := make([][]byte, 0, n)
	for i := 0; i < n; i++ {
		var b []byte
		k := 1 + r.Intn(6)
		for j := 0; j < k; j++ {
			f := all[r.Intn(len(all))]
			if len(f) > 0 && r.Intn(3) == 0 {
				// random sub-slice
				a := r.Intn(len(f))
				c := a + r.Intn(len(f)-a+1)
				f = f[a:c]
			}
			b = append(b, f...)
			for r.Intn(4) == 0 {
				pos := 0
				if len(b) > 0 {
					pos = r.Intn(len(b) + 1)
				}
				c := specials[r.Intn(len(specials))]
				b = append(b[:pos], append([]byte{c}, b[pos:]...)...)
			}
		}
		if r.Intn(5) == 0 && len(b) > 0 {
			b = b[:r.Intn(len(b))]
		}
		out = append(out, b)
	}
	return out
}

func strsToBytes(ss []string) [][]byte {
	out := make([][]byte, len(ss))
	for i, s := range ss {
		out[i] = []byte(s)
	}
	return out
}

