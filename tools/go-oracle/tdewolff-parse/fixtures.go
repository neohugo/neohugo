func genRoot(dir string) {
	fw := newFixture(dir, "root.txt")
	lits := testLiterals("")
	inputs := append(strsToBytes(lits), strsToBytes(rootExtra)...)
	nFixed := len(inputs)
	inputs = append(inputs, fuzz(5, sc(100), lits, rootExtra)...)

	for idx, in := range inputs {
		rootRecords(fw, in, idx < nFixed || idx%5 == 0)
	}
	// long lines for positionContext cut-offs
	r := rand.New(rand.NewSource(6))
	for i := 0; i < sc(120); i++ {
		n := 1 + r.Intn(150)
		var b []byte
		for j := 0; j < n; j++ {
			switch r.Intn(10) {
			case 0:
				b = append(b, "\u00ce"...)
			case 1:
				b = append(b, byte(r.Intn(32)))
			case 2:
				b = append(b, '\n')
			case 3:
				b = append(b, 0xFF)
			case 4:
				b = append(b, "\u200f"...)
			default:
				b = append(b, byte('a'+r.Intn(26)))
			}
		}
		off := r.Intn(len(b) + 2)
		line, col, context := parse.Position(bytes.NewBuffer(cp(b)), off)
		fw.line("position", itoa(off), hx(b), itoa(line), itoa(col), hs(context))
	}
	// Printable and IsGraphic over interesting runes
	runes := []rune{-1, 0, 1, 0x1F, ' ', 'a', 0x7E, 0x7F, 0x80, 0x9F, 0xA0, 0xAD, 0x0800, 0x200F, 0x2028, 0x2318, 0xD800, 0xFFFD, 0xFFFE, 0x10FFFF, 0x110000}
	for i := 0; i < sc(400); i++ {
		runes = append(runes, rune(r.Intn(0x110000)))
	}
	for _, rr := range unicode.GraphicRanges {
		for _, r16 := range rr.R16 {
			runes = append(runes, rune(r16.Lo), rune(r16.Lo)-1, rune(r16.Hi), rune(r16.Hi)+1)
		}
		for _, r32 := range rr.R32 {
			runes = append(runes, rune(r32.Lo), rune(r32.Lo)-1, rune(r32.Hi), rune(r32.Hi)+1)
		}
	}
	for _, rr := range runes {
		fw.line("printable", i64(int64(rr)), hs(parse.Printable(rr)), bstr(unicode.IsGraphic(rr)))
	}
	// the encoding tables
	var t1, t2 []byte
	for c := 0; c < 256; c++ {
		t1 = append(t1, '0'+byte(b2i(parse.URLEncodingTable[c])))
		t2 = append(t2, '0'+byte(b2i(parse.DataURIEncodingTable[c])))
	}
	fw.line("table", "url", string(t1))
	fw.line("table", "datauri", string(t2))
	fw.close()
}

// rootRecords writes the root-package records for one input; heavy adds the
// test entity maps, Position and NewError.
func rootRecords(fw *fixtureWriter, in []byte, heavy bool) {
	fw.line("number", hx(in), itoa(parse.Number(in)))
	n, u := parse.Dimension(in)
	fw.line("dimension", hx(in), itoa(n), itoa(u))
	mt, params := parse.Mediatype(cp(in))
	fw.line("mediatype", hx(in), hx(mt), paramsStr(params))
	{
		b := cp(in)
		mediatype, data, err := parse.DataURI(b)
		fw.line("datauri", hx(in), hx(mediatype), hx(data), errStr(err), hx(b))
	}
	q, qn := parse.QuoteEntity(in)
	fw.line("quoteentity", hx(in), itoa(int(q)), itoa(qn))
	{
		b := cp(in)
		out := parse.ReplaceMultipleWhitespace(b)
		fw.line("rmw", hx(in), hx(out), hx(b))
	}
	for _, name := range mapNames() {
		if !heavy && strings.HasPrefix(name, "test") {
			continue
		}
		m := entityMaps[name]
		b := cp(in)
		out := parse.ReplaceEntities(b, m.ents, m.rev)
		fw.line("rent", name, hx(in), hx(out), hx(b))
		b = cp(in)
		out = parse.ReplaceMultipleWhitespaceAndEntities(b, m.ents, m.rev)
		fw.line("rmwe", name, hx(in), hx(out), hx(b))
	}
	{
		b := cp(in)
		out := parse.DecodeURL(b)
		fw.line("decodeurl", hx(in), hx(out), hx(b))
	}
	{
		b := cp(in)
		out := parse.EncodeURL(b, parse.URLEncodingTable)
		fw.line("encodeurl", "url", hx(in), hx(out), hx(b))
		b = cp(in)
		out = parse.EncodeURL(b, parse.DataURIEncodingTable)
		fw.line("encodeurl", "datauri", hx(in), hx(out), hx(b))
	}
	fw.line("appendescape", hx(in), hx(parse.AppendEscape([]byte("pre"), in, []byte{'"', '\''}, '\\')))
	fw.line("trim", hx(in), hx(parse.TrimWhitespace(cp(in))))
	fw.line("tolower", hx(in), hx(parse.ToLower(cp(in))))
	fw.line("isallws", hx(in), bstr(parse.IsAllWhitespace(in)))
	fw.line("equalfold", hx(in), hs("abc"), bstr(parse.EqualFold(in, []byte("abc"))))
	fw.line("equalfold", hx(in), hx(parse.ToLower(cp(in))), bstr(parse.EqualFold(in, parse.ToLower(cp(in)))))
	if !heavy {
		return
	}
	for _, off := range []int{-1, 1, len(in) / 2, len(in) - 1, len(in) + 5} {
		line, col, context := parse.Position(bytes.NewBuffer(cp(in)), off)
		fw.line("position", itoa(off), hx(in), itoa(line), itoa(col), hs(context))
	}
	fw.line("newerror", hx(in), hs(parse.NewError(bytes.NewBuffer(cp(in)), len(in)/2, "message %d", 5).Error()))
}

func readNumberVectors() []string {
	p := os.Getenv("NUMBERS_JSONL")
	if p == "" {
		return nil
	}
	f, err := os.Open(p)
	if err != nil {
		panic(err)
	}
	defer func() { _ = f.Close() }()
	var out []string
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 1<<20), 1<<20)
	for sc.Scan() {
		var m struct {
			In string `json:"in"`
		}
		if err := stdjson.Unmarshal(sc.Bytes(), &m); err != nil {
			panic(err)
		}
		out = append(out, m.In)
	}
	return out
}

