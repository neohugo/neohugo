// chunkReader is an io.Reader (without Bytes()) that returns at most chunk
// bytes per Read and io.EOF at the end, either together with the last data
// or in a separate call.
type chunkReader struct {
	data        []byte
	pos         int
	chunk       int
	eofWithData bool
}

func (r *chunkReader) Read(p []byte) (int, error) {
	if r.pos >= len(r.data) {
		return 0, io.EOF
	}
	n := min(len(p), r.chunk, len(r.data)-r.pos)
	copy(p, r.data[r.pos:r.pos+n])
	r.pos += n
	if r.eofWithData && r.pos >= len(r.data) {
		return n, io.EOF
	}
	return n, nil
}
