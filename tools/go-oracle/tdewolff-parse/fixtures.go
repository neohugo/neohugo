func mapNames() []string {
	var names []string
	for k := range entityMaps {
		names = append(names, k)
	}
	sort.Strings(names)
	return names
}

func genEntities(dir string) {
	fw := newFixture(dir, "entities.txt")
	for _, name := range mapNames() {
		m := entityMaps[name]
		var keys []string
		for k := range m.ents {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			fw.line("ent", name, hs(k), hx(m.ents[k]))
		}
		if m.rev == nil {
			fw.line("revnil", name)
		}
		var rk []int
		for k := range m.rev {
			rk = append(rk, int(k))
		}
		sort.Ints(rk)
		for _, k := range rk {
			fw.line("rev", name, itoa(k), hx(m.rev[byte(k)]))
		}
	}
	fw.close()
}

func paramsStr(params map[string]string) string {
	if params == nil {
		return "-"
	}
	var keys []string
	for k := range params {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b []byte
	for _, k := range keys {
		b = append(b, k...)
		b = append(b, 0)
		b = append(b, params[k]...)
		b = append(b, 1)
	}
	return hx(append([]byte{}, b...))
}

