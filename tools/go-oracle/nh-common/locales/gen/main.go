// Command gen generates crates/nh-common/src/locales/tables.rs, the data of the
// github.com/gohugoio/localescompressed translators ported to Rust (en and th),
// from the Go sources of the module version in go.mod:
//
//	go run ./tools/go-oracle/nh-common/locales/gen -out crates/nh-common/src/locales/tables.rs
//
// It parses locales.autogen.go and currencies.autogen.go with go/parser:
//   - the `localen` struct declaration (every field, in order),
//   - the composite literal of translatorFuncs[<locale>] for each ported locale
//     (string, []string, []locales.PluralRule and map[string]string fields, and
//     the names of the shared fn* functions, which the Rust port implements under
//     the same names in snake case),
//   - every translatorFuncs key (so the port can tell "unknown locale" from
//     "locale Go has but the port does not"),
//   - the currencies map (values taken from localescompressed.GetCurrency).
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/printer"
	"go/token"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/gohugoio/localescompressed"
)

// The locales the Rust port implements.
var ported = []string{"en", "th"}

type field struct {
	name string
	typ  string // Go type expression
}

func main() {
	out := flag.String("out", "crates/nh-common/src/locales/tables.rs", "output Rust file")
	flag.Parse()

	dir := moduleDir("github.com/gohugoio/localescompressed")
	fset := token.NewFileSet()
	lf, err := parser.ParseFile(fset, filepath.Join(dir, "locales.autogen.go"), nil, 0)
	if err != nil {
		log.Fatal(err)
	}
	cf, err := parser.ParseFile(fset, filepath.Join(dir, "currencies.autogen.go"), nil, 0)
	if err != nil {
		log.Fatal(err)
	}

	fields := localenFields(fset, lf)
	lits, names := translatorLiterals(lf)
	codes := currencyCodes(cf)

	var b bytes.Buffer
	b.WriteString("// This file is generated by tools/go-oracle/nh-common/locales/gen from\n")
	fmt.Fprintf(&b, "// github.com/gohugoio/localescompressed %s (locales.autogen.go, currencies.autogen.go).\n", filepath.Base(dir)[len("localescompressed@"):])
	b.WriteString("// DO NOT EDIT.\n\n")
	b.WriteString("use super::fns::*;\n")
	b.WriteString("use super::localen::Localen;\n")
	b.WriteString("use super::PluralRule;\n\n")

	b.WriteString("/// Every key of Go's `translatorFuncs`, sorted.\n")
	b.WriteString("pub(super) const LOCALE_NAMES: &[&str] = &[\n")
	for _, n := range names {
		fmt.Fprintf(&b, "    %s,\n", rustStr(n))
	}
	b.WriteString("];\n\n")

	b.WriteString("/// Go's `currencies` map (ISO 4217 code -> `currency.Type`), sorted by code.\n")
	b.WriteString("pub(super) const CURRENCIES: &[(&str, i64)] = &[\n")
	for _, c := range codes {
		t := localescompressed.GetCurrency(c)
		if t < 0 {
			log.Fatalf("GetCurrency(%q) = %d", c, t)
		}
		fmt.Fprintf(&b, "    (%s, %d),\n", rustStr(c), int(t))
	}
	b.WriteString("];\n")

	for _, loc := range ported {
		lit, ok := lits[loc]
		if !ok {
			log.Fatalf("no translatorFuncs[%q]", loc)
		}
		fmt.Fprintf(&b, "\n/// Go: `translatorFuncs[%q]` (locales.autogen.go).\n", loc)
		fmt.Fprintf(&b, "pub(super) fn new_%s() -> Localen {\n    Localen {\n", loc)
		vals := map[string]ast.Expr{}
		for _, e := range lit.Elts {
			kv := e.(*ast.KeyValueExpr)
			vals[kv.Key.(*ast.Ident).Name] = kv.Value
		}
		for _, f := range fields {
			fmt.Fprintf(&b, "        %s: %s,\n", snake(f.name), rustValue(f, vals[f.name]))
			delete(vals, f.name)
		}
		if len(vals) != 0 {
			log.Fatalf("%s: fields not in localen: %v", loc, vals)
		}
		b.WriteString("    }\n}\n")
	}

	if err := os.WriteFile(*out, b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}

func moduleDir(mod string) string {
	cmd := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", mod)
	cmd.Stderr = os.Stderr
	b, err := cmd.Output()
	if err != nil {
		log.Fatal(err)
	}
	return strings.TrimSpace(string(b))
}

func localenFields(fset *token.FileSet, f *ast.File) []field {
	for _, d := range f.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, s := range gd.Specs {
			ts := s.(*ast.TypeSpec)
			if ts.Name.Name != "localen" {
				continue
			}
			var fields []field
			for _, fl := range ts.Type.(*ast.StructType).Fields.List {
				var tb bytes.Buffer
				if err := printer.Fprint(&tb, fset, fl.Type); err != nil {
					log.Fatal(err)
				}
				for _, n := range fl.Names {
					fields = append(fields, field{name: n.Name, typ: tb.String()})
				}
			}
			return fields
		}
	}
	log.Fatal("no localen struct")
	return nil
}

// translatorLiterals returns the &localen{...} literal of every
// translatorFuncs[<name>] = func() locales.Translator { return &localen{...} }
// assignment in init, and every name, sorted.
func translatorLiterals(f *ast.File) (map[string]*ast.CompositeLit, []string) {
	lits := map[string]*ast.CompositeLit{}
	var names []string
	ast.Inspect(f, func(n ast.Node) bool {
		as, ok := n.(*ast.AssignStmt)
		if !ok || len(as.Lhs) != 1 {
			return true
		}
		ix, ok := as.Lhs[0].(*ast.IndexExpr)
		if !ok {
			return true
		}
		if id, ok := ix.X.(*ast.Ident); !ok || id.Name != "translatorFuncs" {
			return true
		}
		name, err := strconv.Unquote(ix.Index.(*ast.BasicLit).Value)
		if err != nil {
			log.Fatal(err)
		}
		names = append(names, name)
		fl := as.Rhs[0].(*ast.FuncLit)
		ret := fl.Body.List[0].(*ast.ReturnStmt)
		lits[name] = ret.Results[0].(*ast.UnaryExpr).X.(*ast.CompositeLit)
		return false
	})
	sort.Strings(names)
	return lits, names
}

func currencyCodes(f *ast.File) []string {
	var codes []string
	ast.Inspect(f, func(n ast.Node) bool {
		vs, ok := n.(*ast.ValueSpec)
		if !ok || vs.Names[0].Name != "currencies" {
			return true
		}
		for _, e := range vs.Values[0].(*ast.CompositeLit).Elts {
			c, err := strconv.Unquote(e.(*ast.KeyValueExpr).Key.(*ast.BasicLit).Value)
			if err != nil {
				log.Fatal(err)
			}
			codes = append(codes, c)
		}
		return false
	})
	sort.Strings(codes)
	return codes
}

func rustValue(f field, e ast.Expr) string {
	switch {
	case f.typ == "string":
		if e == nil {
			return `""`
		}
		return rustStr(unquote(e))
	case f.typ == "[]string":
		if e == nil {
			return "&[]"
		}
		var parts []string
		for _, el := range e.(*ast.CompositeLit).Elts {
			parts = append(parts, rustStr(unquote(el)))
		}
		return "&[" + strings.Join(parts, ", ") + "]"
	case f.typ == "[]locales.PluralRule":
		if e == nil {
			return "&[]"
		}
		var parts []string
		for _, el := range e.(*ast.CompositeLit).Elts {
			v, err := strconv.Atoi(el.(*ast.BasicLit).Value)
			if err != nil {
				log.Fatal(err)
			}
			parts = append(parts, pluralRule(v))
		}
		return "&[" + strings.Join(parts, ", ") + "]"
	case f.typ == "map[string]string":
		if e == nil {
			return "&[]"
		}
		type kv struct{ k, v string }
		var kvs []kv
		for _, el := range e.(*ast.CompositeLit).Elts {
			p := el.(*ast.KeyValueExpr)
			kvs = append(kvs, kv{unquote(p.Key), unquote(p.Value)})
		}
		sort.Slice(kvs, func(i, j int) bool { return kvs[i].k < kvs[j].k })
		var b strings.Builder
		b.WriteString("&[\n")
		for _, p := range kvs {
			fmt.Fprintf(&b, "            (%s, %s),\n", rustStr(p.k), rustStr(p.v))
		}
		b.WriteString("        ]")
		return b.String()
	case strings.HasPrefix(f.typ, "func("):
		if e == nil {
			log.Fatalf("missing fn field %s", f.name)
		}
		return snake(e.(*ast.Ident).Name)
	}
	log.Fatalf("unsupported field type %s %s", f.name, f.typ)
	return ""
}

func pluralRule(v int) string {
	names := []string{"Unknown", "Zero", "One", "Two", "Few", "Many", "Other"}
	if v < 0 || v >= len(names) {
		log.Fatalf("bad plural rule %d", v)
	}
	return "PluralRule::" + names[v]
}

func unquote(e ast.Expr) string {
	s, err := strconv.Unquote(e.(*ast.BasicLit).Value)
	if err != nil {
		log.Fatal(err)
	}
	return s
}

// rustStr returns a Rust string literal for s (s is valid UTF-8 in these sources).
func rustStr(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"' || r == '\\':
			b.WriteByte('\\')
			b.WriteRune(r)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u{%x}`, r)
		case r >= 0x80 && !unicode.IsPrint(r):
			fmt.Fprintf(&b, `\u{%x}`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

// snake converts a Go identifier (fnFmtDateFull_5b5e...) to Rust snake case.
func snake(s string) string {
	var b strings.Builder
	for i, r := range s {
		if unicode.IsUpper(r) {
			if i > 0 {
				b.WriteByte('_')
			}
			b.WriteRune(unicode.ToLower(r))
			continue
		}
		b.WriteRune(r)
	}
	return b.String()
}
