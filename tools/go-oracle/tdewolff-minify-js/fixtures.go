// Record format of every *.rec.gz fixture (gzip, binary safe):
//
//	#rec N\n
//	then N fields, each: <decimal length>\n<bytes>\n
//
// A `min` record is [cfg, input, output, err, after]:
//   - the input is minified from a private copy buf := cp(input) (Go
//     append growth, so the capacity is Go's) through buffer.NewReader(buf);
//   - err is "" for nil, "PANIC" when Go panicked, else err.Error();
//   - after is "" when buf[:cap(buf)] is unchanged, else "A" + buf[:cap(buf)]
//     (the minifier rewrites its input in place and leaves the NUL sentinel
//     of parse.NewInput in the spare capacity).
//
// A `sub` record is [cfg, prefix, js, suffix, output, err, after]: the js is
// minified from buf[len(prefix):len(prefix)+len(js)] of buf := cp(prefix+js+
// suffix), like the HTML minifier does with a <script> token, and after is
// the whole buf[:cap(buf)] ("" when unchanged).
//
// In digest files (fuzz*) the output, err and after fields are replaced by
// their FNV-1a 64 hex digests.

type recWriter struct {
	f    *os.File
	gz   *gzip.Writer
	w    *bufio.Writer
	n    int
	name string
}

func newRecWriter(dir, name string) *recWriter {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		panic(err)
	}
	p := filepath.Join(dir, name+".rec.gz")
	f, err := os.Create(p)
	if err != nil {
		panic(err)
	}
	gz, _ := gzip.NewWriterLevel(f, gzip.BestCompression)
	w := &recWriter{f: f, gz: gz, w: bufio.NewWriter(gz), name: p}
	w.rec([]byte("# generated by tools/go-oracle/tdewolff-minify-js (" + runtime.Version() + "); DO NOT EDIT"))
	return w
}

func (r *recWriter) rec(fields ...[]byte) {
	_, _ = fmt.Fprintf(r.w, "#rec %d\n", len(fields))
	for _, f := range fields {
		_, _ = fmt.Fprintf(r.w, "%d\n", len(f))
		_, _ = r.w.Write(f)
		_ = r.w.WriteByte('\n')
	}
	r.n++
}

func (r *recWriter) close() {
	if err := r.w.Flush(); err != nil {
		panic(err)
	}
	if err := r.gz.Close(); err != nil {
		panic(err)
	}
	if err := r.f.Close(); err != nil {
		panic(err)
	}
	fmt.Fprintf(os.Stderr, "%s: %d records\n", r.name, r.n-1)
}

func digest(b []byte) []byte {
	h := fnv.New64a()
	h.Write(b)
	return []byte(fmt.Sprintf("%016x", h.Sum64()))
}

// cp is append([]byte(nil), s...) (Go size-class capacity).
func cp(s []byte) []byte { return append([]byte(nil), s...) }

func errField(err error) []byte {
	if err == nil {
		return nil
	}
	if strings.HasPrefix(err.Error(), "PANIC") {
		return []byte("PANIC")
	}
	return []byte(err.Error())
}

// runMin minifies a private copy of in and returns the record fields
// [output, err, after].
func runMin(cfg string, in []byte) [][]byte {
	buf := cp(in)
	pristine := append([]byte(nil), buf[:cap(buf)]...)
	out, err := minifyBuf(cfg, buf)
	var after []byte
	if !bytes.Equal(buf[:cap(buf)], pristine) {
		after = append([]byte("A"), buf[:cap(buf)]...)
	}
	return [][]byte{out, errField(err), after}
}

// runSub minifies the js embedded between prefix and suffix of one buffer
// and returns [output, err, after-of-the-whole-buffer].
func runSub(cfg string, prefix, src, suffix []byte) [][]byte {
	whole := append(append(append([]byte(nil), prefix...), src...), suffix...)
	buf := cp(whole)
	pristine := append([]byte(nil), buf[:cap(buf)]...)
	out, err := minifyBuf(cfg, buf[len(prefix):len(prefix)+len(src)])
	var after []byte
	if !bytes.Equal(buf[:cap(buf)], pristine) {
		after = append([]byte("A"), buf[:cap(buf)]...)
	}
	return [][]byte{out, errField(err), after}
}

func digests(fields [][]byte) [][]byte {
	var d [][]byte
	for _, f := range fields {
		d = append(d, digest(f))
	}
	return d
}

func modCache() string {
	out, err := exec.Command("go", "env", "GOMODCACHE").Output()
	if err != nil {
		panic(err)
	}
	return strings.TrimSpace(string(out))
}

func minifyJSDir() string {
	return filepath.Join(modCache(), "github.com/tdewolff/minify/v2@v2.23.8/js")
}

func parseJSDir() string {
	return filepath.Join(modCache(), "github.com/tdewolff/parse/v2@v2.8.1/js")
}

// testLiterals returns every string literal of the upstream minify/js and
// parse/js test files plus the hand-written cases, deduplicated in order.
func testLiterals() [][]byte {
	var files []string
	for _, dir := range []string{minifyJSDir(), parseJSDir()} {
		m, err := filepath.Glob(filepath.Join(dir, "*_test.go"))
		if err != nil {
			panic(err)
		}
		sort.Strings(m)
		files = append(files, m...)
	}
	seen := map[string]bool{}
	var lits [][]byte
	add := func(s string) {
		if !seen[s] {
			seen[s] = true
			lits = append(lits, []byte(s))
		}
	}
	for _, e := range extraCases {
		add(e)
	}
	for _, e := range notCases() {
		add(e)
	}
	for _, fn := range files {
		fset := token.NewFileSet()
		f, err := parser.ParseFile(fset, fn, nil, 0)
		if err != nil {
			panic(err)
		}
		ast.Inspect(f, func(n ast.Node) bool {
			if bl, ok := n.(*ast.BasicLit); ok && bl.Kind == token.STRING {
				s, err := strconv.Unquote(bl.Value)
				if err == nil {
					add(s)
				}
			}
			return true
		})
	}
	return lits
}

