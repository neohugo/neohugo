// notCases returns `!(X op Y)` in several contexts for many X, Y shapes
// (optimizeUnaryExpr's De Morgan rewrite with its grouping score).
func notCases() []string {
	xs := []string{"a", "a==b", "a!==b", "a|b", "a&&b", "a||b", "(a||b)", "(a&&b)", "a?b:c", "a=b", "!a", "a<b", "a??b", "(a,b)"}
	var out []string
	for _, x := range xs {
		for _, y := range xs {
			for _, op := range []string{"&&", "||"} {
				e := "!(" + x + op + y + ")"
				out = append(out, "x="+e+";if("+e+")f();y="+e+"?1:2;z=a+"+e+";w="+e+"&&c")
			}
		}
	}
	return out
}

// genFixtures writes every fixture file into dir. scale multiplies the
// random case counts; seed selects the random streams.
func genFixtures(dir string, scale int, seed int64) {
	lits := testLiterals()
	cfgs := []string{"v2022", "v2022-inline", "0", "keep", "keep-alpha", "alpha", "keep-alpha-v2019", "keep-alpha-v2014", "p3-v2022"}

	// literals: every literal through every configuration
	w := newRecWriter(dir, "literals")
	for _, src := range lits {
		for _, cfg := range cfgs {
			w.rec(append([][]byte{[]byte("min"), []byte(cfg), src}, runMin(cfg, src)...)...)
		}
	}
	w.close()

	// embedded: scripts inside a larger buffer (NUL sentinel and in-place
	// writes land in the surrounding bytes, as with the HTML minifier)
	w = newRecWriter(dir, "embedded")
	rnd := rand.New(rand.NewSource(seed))
	for k, src := range lits {
		if k%3 != 0 || len(src) == 0 {
			continue
		}
		pre := []byte("<script>")
		suf := []byte("</script><p>tail</p>")
		if rnd.Intn(2) == 0 {
			pre = []byte("<a onclick=\"")
			suf = []byte("\">x</a>")
		}
		cfg := "v2022"
		if rnd.Intn(3) == 0 {
			cfg = "v2022-inline"
		}
		w.rec(append([][]byte{[]byte("sub"), []byte(cfg), pre, src, suf}, runSub(cfg, pre, src, suf)...)...)
	}
	w.close()

	// html: the JS minifier called by the HTML minifier (neohugo's M)
	genHTML(dir, lits, seed+4)

	// adversarial: sort orders, many locals, deep nesting, long chains
	w = newRecWriter(dir, "adversarial")
	for _, src := range adversarialInputs(seed + 5) {
		for _, cfg := range []string{"v2022", "keep-alpha"} {
			w.rec(append([][]byte{[]byte("min"), []byte(cfg), src}, runMin(cfg, src)...)...)
		}
	}
	w.close()

	// grammar: generated programs (hugo config, and a few other
	// configurations for a subset; digests)
	w = newRecWriter(dir, "grammar")
	rnd = rand.New(rand.NewSource(seed + 1))
	for k := 0; k < 2000*scale; k++ {
		src := genProgram(rnd)
		cfg := "v2022"
		switch rnd.Intn(8) {
		case 0:
			cfg = "0"
		case 1:
			cfg = "keep-v2022"
		case 2:
			cfg = "v2022-inline"
		case 3:
			cfg = "alpha-v2019"
		}
		w.rec(append([][]byte{[]byte("min"), []byte(cfg), src}, digests(runMin(cfg, src))...)...)
	}
	w.close()

	// fuzz: mutated literals and mutated generated programs (digests)
	var nonEmpty [][]byte
	for _, l := range lits {
		if 0 < len(l) {
			nonEmpty = append(nonEmpty, l)
		}
	}
	w = newRecWriter(dir, "fuzz")
	rnd = rand.New(rand.NewSource(seed + 2))
	for k := 0; k < 18000*scale; k++ {
		var src []byte
		if rnd.Intn(9) != 0 {
			src = mutate(rnd, nonEmpty)
		} else {
			src = mutateOps(rnd, genProgram(rnd), nonEmpty, 1+rnd.Intn(2))
		}
		cfg := "v2022"
		if rnd.Intn(4) == 0 {
			cfg = cfgs[rnd.Intn(len(cfgs))]
		}
		w.rec(append([][]byte{[]byte("min"), []byte(cfg), src}, digests(runMin(cfg, src))...)...)
	}
	w.close()

	// repo: the neohugo repository's own JS files; a `multi` record is
	// [name, input, (cfg, output, err, after)...] with digests
	repo := repoRoot()
	w = newRecWriter(dir, "repo")
	for _, p := range jsFiles([]string{repo}) {
		src, err := os.ReadFile(p)
		if err != nil {
			panic(err)
		}
		rel, _ := filepath.Rel(repo, p)
		fields := [][]byte{[]byte("multi"), []byte(filepath.ToSlash(rel)), src}
		for _, cfg := range []string{"v2022", "keep-v2022", "0", "v2022-inline"} {
			fields = append(fields, []byte(cfg))
			fields = append(fields, digests(runMin(cfg, src))...)
		}
		w.rec(fields...)
	}
	w.close()

	// corpuswin: random windows of the Go module cache's JS corpus, mutated
	// 0-2 times (digests)
	roots := []string{
		filepath.Join(modCache(), "github.com/tdewolff/minify/v2@v2.23.8"),
		filepath.Join(modCache(), "github.com/evanw/esbuild@v0.25.6"),
		filepath.Join(modCache(), "golang.org/x/tools@v0.34.0"),
		repo,
	}
	paths := jsFiles(roots)
	w = newRecWriter(dir, "corpuswin")
	rnd = rand.New(rand.NewSource(seed + 3))
	for k := 0; k < 3000*scale; k++ {
		src, err := os.ReadFile(paths[rnd.Intn(len(paths))])
		if err != nil {
			panic(err)
		}
		if len(src) == 0 {
			continue
		}
		l := 16
		for l < 16384 && rnd.Intn(4) != 0 {
			l *= 2
		}
		l = 1 + rnd.Intn(l)
		i := rnd.Intn(len(src))
		j := min(len(src), i+l)
		win := mutateOps(rnd, append([]byte(nil), src[i:j]...), nonEmpty, rnd.Intn(3))
		cfg := "v2022"
		if rnd.Intn(5) == 0 {
			cfg = "v2022-inline"
		}
		w.rec(append([][]byte{[]byte("min"), []byte(cfg), win}, digests(runMin(cfg, win))...)...)
	}
	w.close()

	// redteam: a sample of the red-team generators (redteam.go; digests)
	genRedTeamFixture(dir, scale, seed+6)
}

func repoRoot() string {
	out, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}").Output()
	if err != nil {
		panic(err)
	}
	return strings.TrimSpace(string(out))
}

var skipDir = regexp.MustCompile(`(^|/)(\.git|\.claude|node_modules|target)$`)

// jsFiles returns the sorted .js/.mjs/.cjs files under the roots.
func jsFiles(roots []string) []string {
	var paths []string
	for _, root := range roots {
		err := filepath.Walk(root, func(p string, info os.FileInfo, err error) error {
			if err != nil {
				return err
			}
			if info.IsDir() && skipDir.MatchString(filepath.ToSlash(p)) {
				return filepath.SkipDir
			}
			switch filepath.Ext(p) {
			case ".js", ".mjs", ".cjs":
				if info.Mode().IsRegular() {
					paths = append(paths, p)
				}
			}
			return nil
		})
		if err != nil {
			panic(err)
		}
	}
	sort.Strings(paths)
	return paths
}

// corpusDigests writes OUT (TSV): root base name, relative path, input
// digest and size, then for every configuration the digests of the output,
// the error and the buffer-after fields.
func corpusDigests(out string, cfgs, roots []string) {
	f, err := os.Create(out)
	if err != nil {
		panic(err)
	}
	w := bufio.NewWriter(f)
	_, _ = fmt.Fprintf(w, "# generated by tools/go-oracle/tdewolff-minify-js corpus (%s); DO NOT EDIT\n", runtime.Version())
	_, _ = fmt.Fprintf(w, "# root\tpath\tinput\tsize\t%s\n", strings.Join(cfgs, "\t"))
	n := 0
	mc := modCache()
	for _, root := range roots {
		// roots are relative to GOMODCACHE, or "repo" for the neohugo module
		dir := filepath.Join(mc, root)
		if root == "repo" {
			dir = repoRoot()
		}
		for _, p := range jsFiles([]string{dir}) {
			src, err := os.ReadFile(p)
			if err != nil {
				panic(err)
			}
			rel, _ := filepath.Rel(dir, p)
			_, _ = fmt.Fprintf(w, "%s\t%s\t%s\t%d", root, filepath.ToSlash(rel), digest(src), len(src))
			for _, cfg := range cfgs {
				d := digests(runMin(cfg, src))
				_, _ = fmt.Fprintf(w, "\t%s,%s,%s", d[0], d[1], d[2])
			}
			_, _ = fmt.Fprintln(w)
			n++
		}
	}
	if err := w.Flush(); err != nil {
		panic(err)
	}
	if err := f.Close(); err != nil {
		panic(err)
	}
	fmt.Fprintf(os.Stderr, "corpus: %d files\n", n)
}

var vocab = []string{
	" ", "\n", ";", ",", "(", ")", "{", "}", "[", "]", "=", "==", "===", "!", "!=", "!==", "?", ":", "?.", "??",
	"=>", "...", ".", "+", "-", "*", "/", "%", "**", "++", "--", "<", ">", "<=", ">=", "&&", "||", "&", "|", "^", "~",
	"'", "\"", "`", "${", "\\", "/*", "*/", "//", "\\u0061", "\\x41", "\\n", "0", "1", ".5", "1e3", "0x1", "1n",
	"a", "b", "var ", "let ", "const ", "function ", "return ", "if(", "else ", "for(", "while(", "do ", "in ", "of ",
	"new ", "class ", "extends ", "typeof ", "void ", "delete ", "await ", "yield ", "async ", "this", "null", "true",
	"false", "undefined", "Infinity", "NaN", "isNaN(", "Number(", "Math.pow(", "Math.abs(", "Math.trunc(", "import ",
	"export ", "default ", "try{", "catch(e)", "finally", "throw ", "break ", "continue ", "switch(", "case ",
	"/re/g", "</script>", "<!--", "-->", "é", " ", "\x00",
}

func mutate(rnd *rand.Rand, lits [][]byte) []byte {
	src := append([]byte(nil), lits[rnd.Intn(len(lits))]...)
	return mutateOps(rnd, src, lits, 1+rnd.Intn(3))
}

func mutateOps(rnd *rand.Rand, src []byte, lits [][]byte, ops int) []byte {
	for k := 0; k < ops; k++ {
		switch rnd.Intn(6) {
		case 0, 1: // insert a vocabulary token
			i := rnd.Intn(len(src) + 1)
			v := vocab[rnd.Intn(len(vocab))]
			src = append(src[:i:i], append([]byte(v), src[i:]...)...)
		case 2: // delete a range
			if 0 < len(src) {
				i := rnd.Intn(len(src))
				j := i + 1 + rnd.Intn(min(8, len(src)-i))
				src = append(src[:i:i], src[j:]...)
			}
		case 3: // splice with another literal
			o := lits[rnd.Intn(len(lits))]
			i := rnd.Intn(len(src) + 1)
			j := rnd.Intn(len(o) + 1)
			src = append(src[:i:i], o[j:]...)
		case 4: // duplicate a range
			if 0 < len(src) {
				i := rnd.Intn(len(src))
				j := i + 1 + rnd.Intn(min(16, len(src)-i))
				src = append(src[:j:j], append(append([]byte(nil), src[i:j]...), src[j:]...)...)
			}
		case 5: // truncate
			if 0 < len(src) {
				src = src[:rnd.Intn(len(src))]
			}
		}
	}
	return src
}
