"""Generates crates/go-strconv/src/{internal/pow10tab.rs,isprint.rs} from the
go1.27.1 sources ($(go env GOROOT)/src/internal/strconv/pow10tab.go and
src/strconv/isprint.go). Run from anywhere: python3 gentables.py"""
import os, re, subprocess

GR = os.path.join(subprocess.check_output(["go", "env", "GOROOT"], text=True).strip(), "src")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "crates", "go-strconv", "src")

# pow10tab
src = open(GR + "/internal/strconv/pow10tab.go").read()
mn = int(re.search(r"pow10Min = (-?\d+)", src).group(1))
mx = int(re.search(r"pow10Max = (-?\d+)", src).group(1))
rows = re.findall(r"\{(0x[0-9a-f]+), (0x[0-9a-f]+)\}, // (.*)", src)
assert len(rows) == mx - mn + 1, len(rows)
with open(OUT + "/internal/pow10tab.rs", "w") as f:
    f.write("// Code generated from go1.27.1 src/internal/strconv/pow10tab.go\n")
    f.write("// (itself generated by pow10gen.go). DO NOT EDIT.\n\n")
    f.write("use super::uscale::PmHiLo;\n\n")
    f.write("pub(crate) const POW10_MIN: i64 = %d;\n" % mn)
    f.write("#[allow(dead_code)]\npub(crate) const POW10_MAX: i64 = %d;\n\n" % mx)
    f.write("/// pow10Tab holds 128-bit mantissas of powers of 10.\n")
    f.write("/// The values are scaled so the high bit is always set.\n")
    f.write("#[rustfmt::skip]\n")
    f.write("pub(crate) static POW10_TAB: [PmHiLo; %d] = [\n" % len(rows))
    for hi, lo, c in rows:
        f.write("    PmHiLo { hi: %s, lo: %s }, // %s\n" % (hi, lo, c))
    f.write("];\n")

# isprint
src = open(GR + "/strconv/isprint.go").read()
def table(name):
    m = re.search(r"var " + name + r" = \[\](uint16|uint32)\{[^\n]*\n(.*?)\n\}", src, re.S)
    ty = m.group(1)
    vals = re.findall(r"0x[0-9a-f]+", m.group(2))
    return ty, vals
with open(OUT + "/isprint.rs", "w") as f:
    f.write("// Code generated from go1.27.1 src/strconv/isprint.go\n")
    f.write("// (itself generated by makeisprint.go from Unicode 17.0.0 tables). DO NOT EDIT.\n\n")
    for name, rname in [("isPrint16","IS_PRINT16"),("isNotPrint16","IS_NOT_PRINT16"),("isPrint32","IS_PRINT32"),("isNotPrint32","IS_NOT_PRINT32"),("isGraphic","IS_GRAPHIC")]:
        ty, vals = table(name)
        rty = "u16" if ty == "uint16" else "u32"
        if name == "isNotPrint32":
            f.write("// add 0x10000 to each entry\n")
        f.write("#[rustfmt::skip]\npub(crate) static %s: [%s; %d] = [\n" % (rname, rty, len(vals)))
        per = 8
        for i in range(0, len(vals), per):
            f.write("    " + " ".join(v + "," for v in vals[i:i+per]) + "\n")
        f.write("];\n\n")
        print(name, len(vals))
