func create(dir, name string) (*os.File, *bufio.Writer) {
	f, err := os.Create(filepath.Join(dir, name))
	if err != nil {
		log.Fatal(err)
	}
	w := bufio.NewWriter(f)
	_, _ = fmt.Fprintf(w, "# generated by tools/go-oracle/go-strconv (%s)\n", runtime.Version())
	return f, w
}

func closeW(f *os.File, w *bufio.Writer) {
	if err := w.Flush(); err != nil {
		log.Fatal(err)
	}
	if err := f.Close(); err != nil {
		log.Fatal(err)
	}
}

func goTestdata(name string) []string {
	p := filepath.Join(runtime.GOROOT(), "src", "internal", "strconv", "testdata", name)
	data, err := os.ReadFile(p)
	if err != nil {
		log.Fatal(err)
	}
	var lines []string
	for _, l := range strings.Split(string(data), "\n") {
		l = strings.TrimSpace(l)
		if l == "" || strings.HasPrefix(l, "#") {
			continue
		}
		lines = append(lines, l)
	}
	return lines
}

func errCode(err error) string {
	switch {
	case err == nil:
		return "nil"
	case errors.Is(err, strconv.ErrRange):
		return "range"
	case errors.Is(err, strconv.ErrSyntax):
		return "syntax"
	}
	return "other"
}

