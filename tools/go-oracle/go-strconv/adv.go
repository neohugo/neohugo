// parsing: hexadecimal midpoints

func advUnderscoredHex(h string) string {
	var b strings.Builder
	for i := 0; i < len(h); i++ {
		b.WriteByte(h[i])
		if i%2 == 1 && i+1 < len(h) {
			b.WriteByte('_')
		}
	}
	return b.String()
}

func hexForms(x uint64, e2 int) []string {
	h := strconv.FormatUint(x, 16)
	pm := func(e int) string { return "p" + strconv.Itoa(e) }
	forms := []string{
		"0x" + h + pm(e2),
		"0x" + h + "000" + pm(e2-12),
		"0x" + h + "0000001" + pm(e2-28),
		"0x" + strconv.FormatUint(x*16-1, 16) + pm(e2-4),
	}
	if len(h) > 1 {
		forms = append(forms, "0x"+h[:1]+"."+h[1:]+pm(e2+4*(len(h)-1)))
	} else {
		forms = append(forms, "0x"+h+"."+pm(e2))
	}
	exp := strconv.Itoa(e2)
	if e2 >= 0 {
		exp = "+" + exp
	}
	forms = append(forms,
		"0x_"+advUnderscoredHex(h)+pm(e2),
		"-0X"+strings.ToUpper(h)+"P"+exp,
		"0x0.00"+h+pm(e2+4*(2+len(h))),
		"0x"+h+pm(e2-5000),
		"0x"+h+pm(e2+5000),
	)
	return forms
}

func runHexMid(s *sink, r *rng, _ int) {
	emit := func(mids []advMid) {
		for _, m := range mids {
			s.ctx("mid %d %d", m.x, m.e2)
			for _, str := range hexForms(m.x, m.e2) {
				s.parse(str, 64)
				s.parse(str, 32)
			}
		}
	}
	for i := 0; i < 1024; i++ {
		b := genMid64(r)
		s.ctx("value %016x", b)
		emit(floatMids((b>>52)&0x7ff, b&(1<<52-1), 52, -1074))
		b32 := genMid32(r)
		s.ctx("value32 %08x", b32)
		emit(floatMids(uint64(b32>>23)&0xff, uint64(b32)&(1<<23-1), 23, -149))
	}
}

