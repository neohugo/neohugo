// parsing: exact midpoints

// genMid64 returns positive finite float64 bits from a mix of hard classes.
func genMid64(r *rng) uint64 {
	const mask52 = 1<<52 - 1
	switch r.intn(8) {
	case 0, 1:
		b := r.next() &^ (1 << 63)
		if (b>>52)&0x7ff == 0x7ff {
			b &^= 1 << 62
		}
		return b
	case 2: // subnormal
		return r.next() >> uint(12+r.intn(52))
	case 3: // around the smallest normal
		ef := uint64(r.intn(3))
		return ef<<52 | r.next()&mask52
	case 4: // around the largest finite
		ef := uint64(2046 - r.intn(2))
		return ef<<52 | (mask52 - r.next()%8)
	case 5: // powers of two
		return uint64(r.intn(2047)) << 52
	case 6: // moderate
		ef := uint64(1023 - 70 + r.intn(141))
		return ef<<52 | r.next()&mask52
	default:
		ef := uint64(r.intn(2047))
		mants := [8]uint64{0, 1, 2, mask52, mask52 - 1, 1 << 51, 1<<51 - 1, 1<<51 + 1}
		return ef<<52 | mants[r.intn(8)]
	}
}

// genMid32 returns positive finite float32 bits from a mix of hard classes.
func genMid32(r *rng) uint32 {
	const mask23 = 1<<23 - 1
	switch r.intn(8) {
	case 0, 1:
		b := uint32(r.next()) &^ (1 << 31)
		if (b>>23)&0xff == 0xff {
			b &^= 1 << 30
		}
		return b
	case 2:
		return uint32(r.next() >> uint(41+r.intn(23)))
	case 3:
		ef := uint32(r.intn(3))
		return ef<<23 | uint32(r.next())&mask23
	case 4:
		ef := uint32(254 - r.intn(2))
		return ef<<23 | (mask23 - uint32(r.next()%8))
	case 5:
		return uint32(r.intn(255)) << 23
	case 6:
		ef := uint32(127 - 30 + r.intn(61))
		return ef<<23 | uint32(r.next())&mask23
	default:
		ef := uint32(r.intn(255))
		mants := [8]uint32{0, 1, 2, mask23, mask23 - 1, 1 << 22, 1<<22 - 1, 1<<22 + 1}
		return ef<<23 | mants[r.intn(8)]
	}
}

// A midpoint is x * 2**e2.
type advMid struct {
	x  uint64
	e2 int
}

// floatMids returns the midpoints between the float (exponent field ef,
// fraction frac, mantissa width mb, subnormal exponent emin) and its
// neighbours: the upper one always, the lower one if the float is not zero.
func floatMids(ef, frac uint64, mb uint, emin int) []advMid {
	var m uint64
	var e int
	if ef == 0 {
		m, e = frac, emin
	} else {
		m, e = frac|1<<mb, int(ef)+emin-1
	}
	mids := []advMid{{2*m + 1, e - 1}}
	switch {
	case m == 0:
	case frac == 0 && ef > 1:
		mids = append(mids, advMid{4*m - 1, e - 2})
	default:
		mids = append(mids, advMid{2*m - 1, e - 1})
	}
	return mids
}

// exactDecimal returns the digits D and the number of fraction digits of
// x * 2**e2 (value = D / 10**frac).
func exactDecimal(x uint64, e2 int) (string, int) {
	v := new(big.Int).SetUint64(x)
	if e2 >= 0 {
		v.Lsh(v, uint(e2))
		return v.String(), 0
	}
	v.Mul(v, new(big.Int).Exp(big.NewInt(5), big.NewInt(int64(-e2)), nil))
	return v.String(), -e2
}

// advPlain formats digits d with p digits before the decimal point.
func advPlain(d string, p int) string {
	n := len(d)
	switch {
	case p <= 0:
		return "0." + strings.Repeat("0", -p) + d
	case p >= n:
		return d + strings.Repeat("0", p-n)
	default:
		return d[:p] + "." + d[p:]
	}
}

// advSci formats the first k digits of d (p digits before the point) in
// scientific notation with exponent character ec.
func advSci(d string, p, k int, ec string) string {
	if k > len(d) {
		k = len(d)
	}
	m := d[:k]
	var b strings.Builder
	b.WriteByte(m[0])
	if len(m) > 1 {
		b.WriteByte('.')
		b.WriteString(m[1:])
	}
	b.WriteString(ec)
	b.WriteString(strconv.Itoa(p - 1))
	return b.String()
}

// advUnderscored is advSci(d, p, len(d), "e") with '_' after every 4th
// fraction digit (when more digits follow).
func advUnderscored(d string, p int) string {
	var b strings.Builder
	b.WriteByte(d[0])
	if len(d) > 1 {
		b.WriteByte('.')
		for i := 1; i < len(d); i++ {
			b.WriteByte(d[i])
			if i%4 == 0 && i+1 < len(d) {
				b.WriteByte('_')
			}
		}
	}
	b.WriteString("e")
	b.WriteString(strconv.Itoa(p - 1))
	return b.String()
}

// advDecrement subtracts one unit in the last place of the decimal digit
// string d (d > 0), keeping its length.
func advDecrement(d string) string {
	b := []byte(d)
	for i := len(b) - 1; i >= 0; i-- {
		if b[i] > '0' {
			b[i]--
			break
		}
		b[i] = '9'
	}
	return string(b)
}

func midForms(d string, frac int) []string {
	n := len(d)
	p := n - frac
	plain := advPlain(d, p)
	up := plain + "000001"
	if frac == 0 {
		up = plain + ".000001"
	}
	down := advPlain(advDecrement(d)+"999999", p)
	forms := []string{
		plain,
		advSci(d, p, n, "e"),
		up,
		down,
	}
	for _, k := range [4]int{17, 19, 20, 25} {
		if k < n {
			forms = append(forms, advSci(d, p, k, "e"))
		}
	}
	padded := "+000" + plain
	if frac > 0 {
		padded += "000"
	}
	forms = append(forms,
		advUnderscored(d, p),
		padded,
		"-"+advSci(d, p, n, "E"),
	)
	if p-1 >= 0 {
		forms = append(forms, advSci(d, p, n, "E+"))
	}
	return forms
}

func runMidpoints(s *sink, r *rng, _ int) {
	emit := func(mids []advMid) {
		for _, m := range mids {
			d, frac := exactDecimal(m.x, m.e2)
			s.ctx("mid %d %d", m.x, m.e2)
			for _, str := range midForms(d, frac) {
				s.parse(str, 64)
				s.parse(str, 32)
			}
		}
	}
	for i := 0; i < 256; i++ {
		b := genMid64(r)
		s.ctx("value %016x", b)
		emit(floatMids((b>>52)&0x7ff, b&(1<<52-1), 52, -1074))
	}
	for i := 0; i < 128; i++ {
		b := genMid32(r)
		s.ctx("value32 %08x", b)
		emit(floatMids(uint64(b>>23)&0xff, uint64(b)&(1<<23-1), 23, -149))
	}
}

