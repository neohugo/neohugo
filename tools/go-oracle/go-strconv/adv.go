type advDef struct {
	name   string
	seed   uint64
	chunks int
	run    func(s *sink, r *rng, c int)
}

var advTests = []advDef{
	{"f32all", 101, 1024, runF32All},
	{"f64pow2", 102, 32, runF64Pow2},
	{"ties", 103, 64, runTies},
	{"nearshort", 104, 64, runNearShort},
	{"midpoints", 105, 64, runMidpoints},
	{"hexmid", 106, 32, runHexMid},
	{"quote2", 107, 1, runQuote2},
	{"quote3", 108, 256, runQuote3},
	{"quote4", 109, 16, runQuote4},
	{"unqesc", 110, 18, runUnqEsc},
	{"atoiall", 111, 17, runAtoiAll},
	{"atoibound", 112, 4, runAtoiBound},
	{"longties", 113, 16, runLongTies},
	{"fmtbytes", 114, 4, runFmtBytes},
	{"complex", 115, 8, runComplex},
	{"wildrunes", 116, 16, runWildRunes},
}

// writeAdvHashes computes the chunk hashes of advTests. If only is not
// empty (comma-separated family names), only those families are recomputed
// and the other lines are kept from the existing out file.
func writeAdvHashes(out, only string) {
	type job struct{ t, c int }
	keep := map[string]bool{}
	if only != "" {
		for _, n := range strings.Split(only, ",") {
			keep[n] = true
		}
	}
	old := map[string]string{}
	if only != "" {
		data, err := os.ReadFile(out)
		if err != nil {
			log.Fatal(err)
		}
		for _, l := range strings.Split(string(data), "\n") {
			f := strings.Fields(l)
			if len(f) == 3 && !strings.HasPrefix(l, "#") {
				old[f[0]+" "+f[1]] = f[2]
			}
		}
	}
	results := make([][]uint64, len(advTests))
	var jobs []job
	for ti, t := range advTests {
		results[ti] = make([]uint64, t.chunks)
		if only != "" && !keep[t.name] {
			continue
		}
		for c := 0; c < t.chunks; c++ {
			jobs = append(jobs, job{ti, c})
		}
	}
	strconvOptimize = true
	ch := make(chan job)
	var wg sync.WaitGroup
	for w := 0; w < runtime.NumCPU(); w++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			for j := range ch {
				t := advTests[j.t]
				s := newSink(nil)
				t.run(s, chunkRng(t.seed, j.c), j.c)
				results[j.t][j.c] = s.h
			}
		}()
	}
	for _, j := range jobs {
		ch <- j
	}
	close(ch)
	wg.Wait()

	f, err := os.Create(out)
	if err != nil {
		log.Fatal(err)
	}
	w := bufio.NewWriter(f)
	_, _ = fmt.Fprintf(w, "# generated by tools/go-oracle/go-strconv -mode advhashes (%s); test chunk fnv1a64\n", runtime.Version())
	for ti, t := range advTests {
		for c, h := range results[ti] {
			if only != "" && !keep[t.name] {
				o, ok := old[fmt.Sprintf("%s %d", t.name, c)]
				if !ok {
					log.Fatalf("%s %d: not in %s; regenerate without -only", t.name, c, out)
				}
				_, _ = fmt.Fprintf(w, "%s %d %s\n", t.name, c, o)
				continue
			}
			_, _ = fmt.Fprintf(w, "%s %d %016x\n", t.name, c, h)
		}
	}
	if err := w.Flush(); err != nil {
		log.Fatal(err)
	}
	if err := f.Close(); err != nil {
		log.Fatal(err)
	}
}

func advDump(name string, chunk int) {
	for _, t := range advTests {
		if t.name == name {
			w := bufio.NewWriter(os.Stdout)
			s := newSink(w)
			t.run(s, chunkRng(t.seed, chunk), chunk)
			_, _ = fmt.Fprintf(w, "hash %016x\n", s.h)
			_ = w.Flush()
			return
		}
	}
	log.Fatalf("unknown adv test %q", name)
}

func (s *sink) parse(str string, bs int) {
	v, err := strconv.ParseFloat(str, bs)
	s.ctx("parse %s %d", str, bs)
	s.putU64(math.Float64bits(v))
	s.putErr(err)
}

