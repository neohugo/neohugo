package main

// Adversarial differential tests (added by the independent verification
// pass). Like tests.go, every test is split into chunks and each chunk is
// reduced to one FNV-1a hash. The Rust mirror is
// crates/go-strconv/tests/adv.rs; any change here must be mirrored there.
//
// Families:
//
//	f32all     every float32 bit pattern (2^32): shortest 'e', its
//	           ParseFloat(.., 32) round trip, and two fixed precisions.
//	f64pow2    every float64 exponent x {0,1,2,3,2^51,2^52-1,2^52-2}
//	           mantissas x both signs, through all formats and many precs.
//	ties       exact decimal ties n*2^-k (and (10j+5)*10^q integers) at
//	           every precision that can round on them.
//	nearshort  floats nearest to short decimals and their +-1, +-2 ulp
//	           neighbours (shortest-format boundary cases).
//	midpoints  exact decimal midpoints between adjacent float64/float32
//	           values (up to ~770 digits) and near-midpoint perturbations,
//	           in plain, scientific, underscored, padded and truncated forms.
//	hexmid     hexadecimal midpoints, sticky bits, >16 hex digits, extreme
//	           exponents.
//	quote2     every string of 0, 1 and 2 bytes through all quoting funcs.
//	quote3     every 3-byte string (16.7M).
//	quote4     4-byte strings: any first byte, then 3 bytes from a set of
//	           16 UTF-8 boundary/special values.
//	unqesc     \U, \u, \x and octal escapes over their whole value range.
//	atoiall    every string of length <= 4 over a 16-char alphabet, through
//	           ParseInt/ParseUint for 11 bases x 11 bit sizes, Atoi, ParseBool.
//	atoibound  2^k+-d boundaries for every bit size, in bases 2/8/10/16/36,
//	           with and without prefixes and underscores.
//	longties   exact midpoints followed by >800 zeros and a final 1 (or
//	           decremented and followed by >800 nines): the slow path's
//	           800-digit truncation at an exact tie.
//	fmtbytes   every fmt byte 0..255 through AppendFloat (FormatFloat for
//	           ASCII) at several precisions and both bit sizes.
//	complex    FormatComplex over all formats/precisions and its
//	           ParseComplex round trip.
//	wildrunes  IsPrint/IsGraphic/QuoteRune* of negative and >MaxRune runes
//	           whose low 16 bits are special (int32 -> uint16 truncation).

