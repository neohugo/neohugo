// longTieForms returns near-tie strings for the midpoint digits d (frac
// fraction digits) that are longer than the 800-digit decimal buffer.
func longTieForms(d string, frac int) []string {
	p := len(d) - frac
	plain := advPlain(d, p)
	dot := ""
	if frac == 0 {
		dot = "."
	}
	return []string{
		plain + dot + strings.Repeat("0", 820) + "1",
		plain + dot + strings.Repeat("0", 820),
		advPlain(advDecrement(d)+strings.Repeat("9", 820), p),
		strings.Repeat("0", 790) + plain + dot + "1",
		"-" + plain + dot + strings.Repeat("0", 820) + "1",
		d[:1] + "." + d[1:] + strings.Repeat("0", 850) + "1e" + strconv.Itoa(p-1),
	}
}

func runLongTies(s *sink, r *rng, _ int) {
	emit := func(mids []advMid) {
		for _, m := range mids {
			d, frac := exactDecimal(m.x, m.e2)
			s.ctx("mid %d %d", m.x, m.e2)
			for _, str := range longTieForms(d, frac) {
				s.parse(str, 64)
				s.parse(str, 32)
			}
		}
	}
	for i := 0; i < 64; i++ {
		b := genMid64(r)
		s.ctx("value %016x", b)
		emit(floatMids((b>>52)&0x7ff, b&(1<<52-1), 52, -1074))
		b32 := genMid32(r)
		s.ctx("value32 %08x", b32)
		emit(floatMids(uint64(b32>>23)&0xff, uint64(b32)&(1<<23-1), 23, -149))
	}
}

var fmtBytesPrecs = [10]int{-5, -1, 0, 1, 5, 17, 18, 30, 400, 1100}

func runFmtBytes(s *sink, r *rng, c int) {
	for fm := c * 64; fm < c*64+64; fm++ {
		for i := 0; i < 32; i++ {
			f := math.Float64frombits(genF64(r))
			for _, prec := range fmtBytesPrecs {
				for _, bs := range [2]int{64, 32} {
					s.ctx("fmt %d value %016x prec %d bs %d", fm, math.Float64bits(f), prec, bs)
					s.put(strconv.AppendFloat([]byte("x"), f, byte(fm), prec, bs))
				}
			}
		}
	}
}

func runComplex(s *sink, r *rng, _ int) {
	for i := 0; i < 1<<11; i++ {
		re := math.Float64frombits(genF64(r))
		im := math.Float64frombits(genF64(r))
		v := complex(re, im)
		s.ctx("complex %016x %016x", math.Float64bits(re), math.Float64bits(im))
		for j := 0; j < len(fmts); j++ {
			for _, prec := range [4]int{-1, 0, 3, 17} {
				for _, bs := range [2]int{128, 64} {
					str := strconv.FormatComplex(v, fmts[j], prec, bs)
					s.putStr(str)
					if prec == -1 && fmts[j] != 'b' {
						p, err := strconv.ParseComplex(str, bs)
						s.putU64(math.Float64bits(real(p)))
						s.putU64(math.Float64bits(imag(p)))
						s.putErr(err)
					}
				}
			}
		}
	}
}

var wildLows = [24]uint32{
	0x0000, 0x0020, 0x0041, 0x007e, 0x007f, 0x00a0, 0x00ad, 0x0378,
	0x1680, 0x2000, 0x200a, 0x2028, 0x202f, 0x205f, 0x3000, 0xd800,
	0xdfff, 0xe000, 0xf8ff, 0xfeff, 0xfffd, 0xffff, 0x0085, 0x00ff,
}

func runWildRunes(s *sink, _ *rng, c int) {
	for hi := c * 4096; hi < c*4096+4096; hi++ {
		for _, lo := range wildLows {
			x := rune(int32(uint32(hi)<<16 | lo))
			s.ctx("rune %d", x)
			s.putBool(strconv.IsPrint(x))
			s.putBool(strconv.IsGraphic(x))
			s.putStr(strconv.QuoteRune(x))
			s.putStr(strconv.QuoteRuneToASCII(x))
			s.putStr(strconv.QuoteRuneToGraphic(x))
		}
	}
}
