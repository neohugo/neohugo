const atoiAlphabet = "01789abfxXoO_+-z"

var atoiBases = [11]int{-1, 0, 1, 2, 3, 8, 10, 16, 35, 36, 37}
var atoiBits = [11]int{-1, 0, 1, 7, 8, 9, 16, 32, 63, 64, 65}

func atoiOps(s *sink, str string) {
	s.ctx("input %q", str)
	for _, base := range atoiBases {
		for _, bits := range atoiBits {
			v, err := strconv.ParseInt(str, base, bits)
			s.putU64(uint64(v))
			s.putErr(err)
			u, err := strconv.ParseUint(str, base, bits)
			s.putU64(u)
			s.putErr(err)
		}
	}
	v, err := strconv.Atoi(str)
	s.putU64(uint64(v))
	s.putErr(err)
	b, err := strconv.ParseBool(str)
	s.putBool(b)
	s.putErr(err)
}

func runAtoiAll(s *sink, _ *rng, c int) {
	if c < 16 {
		for i := 0; i < 16*16*16; i++ {
			str := []byte{atoiAlphabet[c], atoiAlphabet[i>>8], atoiAlphabet[(i>>4)&15], atoiAlphabet[i&15]}
			atoiOps(s, string(str))
		}
		return
	}
	atoiOps(s, "")
	for n := 1; n <= 3; n++ {
		total := 1 << (4 * n)
		for i := 0; i < total; i++ {
			str := make([]byte, n)
			for j := 0; j < n; j++ {
				str[j] = atoiAlphabet[(i>>(4*(n-1-j)))&15]
			}
			atoiOps(s, string(str))
		}
	}
}

var boundBases = [5]int{2, 8, 10, 16, 36}

func runAtoiBound(s *sink, _ *rng, c int) {
	for bits := c*16 + 1; bits <= c*16+16; bits++ {
		for _, sh := range [2]int{bits - 1, bits} {
			for d := int64(-2); d <= 2; d++ {
				for _, neg := range [2]bool{false, true} {
					v := new(big.Int).Lsh(big.NewInt(1), uint(sh))
					v.Add(v, big.NewInt(d))
					if neg {
						v.Neg(v)
					}
					for _, base := range boundBases {
						digits := v.Text(base)
						sign := ""
						if digits[0] == '-' {
							sign, digits = "-", digits[1:]
						}
						prefix := ""
						switch base {
						case 2:
							prefix = "0b"
						case 8:
							prefix = "0o"
						case 16:
							prefix = "0x"
						}
						strs := []string{sign + digits}
						if prefix != "" || base == 10 {
							us := advUnderscoredHex(digits)
							strs = append(strs, sign+prefix+digits, sign+prefix+"_"+us, sign+prefix+us+"_")
						}
						for _, str := range strs {
							s.ctx("bound %s base %d bits %d", str, base, bits)
							for _, b := range [2]int{base, 0} {
								for _, bs := range [3]int{bits, 64, 0} {
									iv, err := strconv.ParseInt(str, b, bs)
									s.putU64(uint64(iv))
									s.putErr(err)
									uv, err := strconv.ParseUint(str, b, bs)
									s.putU64(uv)
									s.putErr(err)
								}
							}
							iv, err := strconv.Atoi(str)
							s.putU64(uint64(iv))
							s.putErr(err)
						}
					}
				}
			}
		}
	}
}

