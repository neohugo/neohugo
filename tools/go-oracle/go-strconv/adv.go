func runF32All(s *sink, _ *rng, c int) {
	for b := uint32(c) << 22; ; b++ {
		f := float64(math.Float32frombits(b))
		s.ctx("value %08x", b)
		e1 := strconv.FormatFloat(f, 'e', -1, 32)
		s.putStr(e1)
		v, err := strconv.ParseFloat(e1, 32)
		s.putU64(math.Float64bits(v))
		s.putErr(err)
		s.putStr(strconv.FormatFloat(f, 'e', 8, 32))
		s.putStr(strconv.FormatFloat(f, 'e', 5, 32))
		if b&(1<<22-1) == 1<<22-1 {
			break
		}
	}
}

var pow2Mants = [7]uint64{0, 1, 2, 3, 1 << 51, 1<<52 - 1, 1<<52 - 2}

var pow2FPrecs = [9]int{0, 1, 2, 3, 5, 10, 17, 20, 30}

func runF64Pow2(s *sink, _ *rng, c int) {
	for exp := uint64(c * 64); exp < uint64(c*64+64); exp++ {
		for sign := uint64(0); sign < 2; sign++ {
			for _, mant := range pow2Mants {
				b := sign<<63 | exp<<52 | mant
				f := math.Float64frombits(b)
				s.ctx("value %016x", b)
				for i := 0; i < len(fmts); i++ {
					s.putStr(strconv.FormatFloat(f, fmts[i], -1, 64))
				}
				for prec := 0; prec <= 20; prec++ {
					s.putStr(strconv.FormatFloat(f, 'e', prec, 64))
					s.putStr(strconv.FormatFloat(f, 'g', prec, 64))
				}
				for _, prec := range pow2FPrecs {
					s.putStr(strconv.FormatFloat(f, 'f', prec, 64))
				}
				for prec := 0; prec <= 14; prec++ {
					s.putStr(strconv.FormatFloat(f, 'x', prec, 64))
				}
				s.putStr(strconv.FormatFloat(f, 'e', -1, 32))
				s.putStr(strconv.FormatFloat(f, 'g', 9, 32))
				s.putStr(strconv.FormatFloat(f, 'x', -1, 32))
				strs := [3]string{
					strconv.FormatFloat(f, 'g', -1, 64),
					strconv.FormatFloat(f, 'x', -1, 64),
					strconv.FormatFloat(f, 'e', 16, 64),
				}
				for _, str := range strs {
					s.parse(str, 64)
					s.parse(str, 32)
				}
			}
		}
	}
}

func runTies(s *sink, _ *rng, c int) {
	k := c + 1
	for n := 1; n <= 2001; n += 2 {
		f := math.Ldexp(float64(n), -k)
		s.ctx("tie %d %d", n, k)
		for prec := 0; prec <= 50; prec++ {
			s.putStr(strconv.FormatFloat(f, 'e', prec, 64))
		}
		for prec := 0; prec <= k+2; prec++ {
			s.putStr(strconv.FormatFloat(f, 'f', prec, 64))
		}
		for prec := 1; prec <= 30; prec++ {
			s.putStr(strconv.FormatFloat(f, 'g', prec, 64))
		}
		for prec := 0; prec <= 30; prec++ {
			s.putStr(strconv.FormatFloat(f, 'e', prec, 32))
		}
	}
	q := c % 16
	for j := 0; j < 1000; j++ {
		n := uint64(10*j+5) * pow10u[q]
		f := float64(n)
		s.ctx("inttie %d", n)
		for prec := 0; prec <= 20; prec++ {
			s.putStr(strconv.FormatFloat(f, 'e', prec, 64))
			s.putStr(strconv.FormatFloat(f, 'g', prec+1, 64))
		}
		s.putStr(strconv.FormatFloat(f, 'f', 0, 64))
		s.putStr(strconv.FormatFloat(f, 'f', 2, 64))
		for prec := 0; prec <= 12; prec++ {
			s.putStr(strconv.FormatFloat(f, 'e', prec, 32))
		}
	}
}

func nearShortOps(s *sink, g float64, bs, nd int) {
	e1 := strconv.FormatFloat(g, 'e', -1, bs)
	s.putStr(e1)
	s.parse(e1, bs)
	s.putStr(strconv.FormatFloat(g, 'e', nd-1, bs))
	if nd >= 2 {
		s.putStr(strconv.FormatFloat(g, 'e', nd-2, bs))
	}
	s.putStr(strconv.FormatFloat(g, 'g', nd, bs))
	s.putStr(strconv.FormatFloat(g, 'f', -1, bs))
}

func runNearShort(s *sink, r *rng, _ int) {
	for i := 0; i < 1<<12; i++ {
		nd := 1 + r.intn(17)
		n := pow10u[nd-1] + r.next()%(9*pow10u[nd-1])
		q := r.intn(660) - 350
		str := strconv.FormatUint(n, 10) + "e" + strconv.Itoa(q)
		f, _ := strconv.ParseFloat(str, 64)
		s.ctx("near %s", str)
		b0 := math.Float64bits(f)
		for d := -2; d <= 2; d++ {
			b := b0 + uint64(int64(d))
			s.ctx("value %016x", b)
			nearShortOps(s, math.Float64frombits(b), 64, nd)
		}
		nd32 := 1 + r.intn(9)
		n32 := pow10u[nd32-1] + r.next()%(9*pow10u[nd32-1])
		q32 := r.intn(100) - 55
		str32 := strconv.FormatUint(n32, 10) + "e" + strconv.Itoa(q32)
		f32, _ := strconv.ParseFloat(str32, 32)
		s.ctx("near32 %s", str32)
		b32 := math.Float32bits(float32(f32))
		for d := -2; d <= 2; d++ {
			b := b32 + uint32(int32(d))
			s.ctx("value %08x", b)
			nearShortOps(s, float64(math.Float32frombits(b)), 32, nd32)
		}
	}
}

