func runQuote2(s *sink, _ *rng, _ int) {
	quoteOps(s, nil)
	for a := 0; a < 256; a++ {
		quoteOps(s, []byte{byte(a)})
	}
	for a := 0; a < 256; a++ {
		for b := 0; b < 256; b++ {
			quoteOps(s, []byte{byte(a), byte(b)})
		}
	}
}

func runQuote3(s *sink, _ *rng, c int) {
	for b := 0; b < 256; b++ {
		for d := 0; d < 256; d++ {
			quoteOps(s, []byte{byte(c), byte(b), byte(d)})
		}
	}
}

var quote4Set = [16]byte{0x00, 0x0a, 0x22, 0x27, 0x30, 0x5c, 0x60, 0x78, 0x7f, 0x80, 0x8f, 0x90, 0x9f, 0xa0, 0xbf, 0xc0}

func runQuote4(s *sink, _ *rng, c int) {
	for a := c * 16; a < c*16+16; a++ {
		for _, b := range quote4Set {
			for _, d := range quote4Set {
				for _, e := range quote4Set {
					quoteOps(s, []byte{byte(a), b, d, e})
				}
			}
		}
	}
}

func (s *sink) unquote(str string) {
	u, err := strconv.Unquote(str)
	s.ctx("unquote %x", str)
	s.putStr(u)
	s.putErr(err)
}

func runUnqEsc(s *sink, _ *rng, c int) {
	if c < 17 {
		for v := c << 16; v < (c+1)<<16; v++ {
			s.unquote(fmt.Sprintf(`"\U%08x"`, v))
			s.unquote(fmt.Sprintf(`'\U%08X'`, v))
			s.unquote(fmt.Sprintf(`"a\U%08xb"`, v))
			if v < 0x10000 {
				s.unquote(fmt.Sprintf(`"\u%04x"`, v))
				s.unquote(fmt.Sprintf(`'\u%04X'`, v))
				s.unquote(fmt.Sprintf("`\\u%04x`", v))
			}
			val, mb, tail, err := strconv.UnquoteChar(fmt.Sprintf(`\U%08xz`, v), '"')
			s.putU64(uint64(int64(val)))
			s.putBool(mb)
			s.putU64(uint64(len(tail)))
			s.putErr(err)
		}
		return
	}
	for v := 0; v < 256; v++ {
		b := string([]byte{byte(v)})
		s.unquote(fmt.Sprintf(`"\x%02x"`, v))
		s.unquote(fmt.Sprintf(`"\x%02X"`, v))
		s.unquote(fmt.Sprintf(`'\x%02x'`, v))
		s.unquote("\"\\" + b + "\"")
		s.unquote("'\\" + b + "'")
		s.unquote("\"\\" + b + "00\"")
		s.unquote("\"\\x" + b + "0\"")
		s.unquote("\"\\u00" + b + "0\"")
	}
	for v := 0; v < 512; v++ {
		s.unquote(fmt.Sprintf(`"\%03o"`, v))
		s.unquote(fmt.Sprintf(`'\%03o'`, v))
	}
}

