//! Module `locales`.
//!
//! PORT gohugoio/locales + gohugoio/localescompressed subset: Translator trait + generated en/th tables
//!
//! Owner: Wave B task T26 (common-thirdparty-ports).

//! Subset of `github.com/gohugoio/locales` (+ `localescompressed`): the `Translator` API used by
//! `htime.TimeFormatter` and `lang.FormatNumber*`, with generated data for the languages in use.
//! Generate the tables from the Go module (`localescompressed/locales.autogen.go`) with a small Go
//! program; do not hand-write them. Needed now: en, th (plus the fallback rules of GetTranslator).
//!
//! Upstream: `github.com/gohugoio/locales v0.14.0` (`rules.go`: `Translator`, `PluralRule`;
//! `currency/currency.go`) and `github.com/gohugoio/localescompressed v1.0.1` (`locales.go`:
//! `GetTranslator`, `GetCurrency`; `localen.go`: the `localen` translator; `locales.autogen.go`:
//! the per-locale data and the shared `fn*` implementations). neohugo reaches the translators only
//! through `localescompressed`, so that is what is ported (its `localen` methods differ from the
//! per-locale packages in places, e.g. `MonthsAbbreviated` keeps the leading empty entry).
//!
//! Layout:
//! - `locales/tables.rs`: generated by `tools/go-oracle/nh-common/locales/gen` (every locale
//!   name, the currency map, and the `translatorFuncs["en"]`/`["th"]` literals).
//! - `locales/localen.rs`: the `localen` struct and its `Translator` methods (localen.go).
//! - `locales/fns.rs`: the shared `fn*` functions that en and th use (locales.autogen.go).
//!
//! Only en and th are ported. [`get_translator`] returns an explicit "not supported" error for
//! any other locale that Go knows, and `Ok(None)` for locales Go does not know (Go's `nil`).
//!
//! Go panics reproduced: `FmtNumber`/`FmtCurrency`/`FmtAccounting` slice
//! `s[:len(s)-int(v)-1]`, which panics for NaN (precision ≥ 3) and ±Inf (precision ≥ 4); an
//! unknown currency indexes `currencies[-1]`. The `try_fmt_*` methods return these panics as
//! errors with Go's runtime message (what text/template's `safeCall` reports); the `fmt_*`
//! methods panic like Go.

