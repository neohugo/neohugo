/// Go: `locales.PluralRule`.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum PluralRule {
    Unknown = 0,
    Zero = 1,
    One = 2,
    Two = 3,
    Few = 4,
    Many = 5,
    Other = 6,
}

impl PluralRule {
    // Go: locales rules.go:PluralRule.String
    /// String returns the string value of PluralRule.
    pub fn string(self) -> &'static str {
        const PLURALS_STRING: &str = "UnknownZeroOneTwoFewManyOther";
        match self {
            PluralRule::Zero => &PLURALS_STRING[7..11],
            PluralRule::One => &PLURALS_STRING[11..14],
            PluralRule::Two => &PLURALS_STRING[14..17],
            PluralRule::Few => &PLURALS_STRING[17..20],
            PluralRule::Many => &PLURALS_STRING[20..24],
            PluralRule::Other => &PLURALS_STRING[24..],
            PluralRule::Unknown => &PLURALS_STRING[..7],
        }
    }
}

/// Go: `locales.Translator`.
///
/// Months are Go `time.Month` values (1..=12) and weekdays Go `time.Weekday` values (0 = Sunday
/// ..= 6); other values index out of range and panic, as in Go. `currency` is an ISO 4217 code,
/// resolved like `localescompressed.GetCurrency` (see [`get_currency`]).
pub trait Translator: Send + Sync {
    fn locale(&self) -> &str;
    fn plurals_cardinal(&self) -> &[PluralRule];
    fn plurals_ordinal(&self) -> &[PluralRule];
    fn plurals_range(&self) -> &[PluralRule];
    fn cardinal_plural_rule(&self, num: f64, v: u64) -> PluralRule;
    fn ordinal_plural_rule(&self, num: f64, v: u64) -> PluralRule;
    fn range_plural_rule(&self, num1: f64, v1: u64, num2: f64, v2: u64) -> PluralRule;
    /// `m` is 1..=12.
    fn month_abbreviated(&self, m: u32) -> &str;
    fn months_abbreviated(&self) -> &[&str];
    fn month_narrow(&self, m: u32) -> &str;
    fn months_narrow(&self) -> &[&str];
    fn month_wide(&self, m: u32) -> &str;
    fn months_wide(&self) -> &[&str];
    /// `d` is 0 (Sunday)..=6.
    fn weekday_abbreviated(&self, d: u32) -> &str;
    fn weekdays_abbreviated(&self) -> &[&str];
    fn weekday_narrow(&self, d: u32) -> &str;
    fn weekdays_narrow(&self) -> &[&str];
    fn weekday_short(&self, d: u32) -> &str;
    fn weekdays_short(&self) -> &[&str];
    fn weekday_wide(&self, d: u32) -> &str;
    fn weekdays_wide(&self) -> &[&str];
    fn fmt_date_short(&self, t: &Time) -> String;
    fn fmt_date_medium(&self, t: &Time) -> String;
    fn fmt_date_long(&self, t: &Time) -> String;
    fn fmt_date_full(&self, t: &Time) -> String;
    fn fmt_time_short(&self, t: &Time) -> String;
    fn fmt_time_medium(&self, t: &Time) -> String;
    fn fmt_time_long(&self, t: &Time) -> String;
    fn fmt_time_full(&self, t: &Time) -> String;
    /// Panics where Go panics; see [`Translator::try_fmt_number`].
    fn fmt_number(&self, n: f64, v: u64) -> String {
        or_panic(self.try_fmt_number(n, v))
    }
    fn fmt_percent(&self, n: f64, v: u64) -> String;
    /// Panics where Go panics; see [`Translator::try_fmt_currency`].
    fn fmt_currency(&self, n: f64, v: u64, currency: &str) -> String {
        or_panic(self.try_fmt_currency(n, v, currency))
    }
    /// Panics where Go panics; see [`Translator::try_fmt_accounting`].
    fn fmt_accounting(&self, n: f64, v: u64, currency: &str) -> String {
        or_panic(self.try_fmt_accounting(n, v, currency))
    }
    /// `FmtNumber`, with Go's runtime panic returned as an error.
    fn try_fmt_number(&self, n: f64, v: u64) -> Result<String>;
    /// `FmtCurrency`, with Go's runtime panic returned as an error.
    fn try_fmt_currency(&self, n: f64, v: u64, currency: &str) -> Result<String>;
    /// `FmtAccounting`, with Go's runtime panic returned as an error.
    fn try_fmt_accounting(&self, n: f64, v: u64, currency: &str) -> Result<String>;
}

fn or_panic(r: Result<String>) -> String {
    match r {
        Ok(s) => s,
        Err(e) => panic!("{}", e.message()),
    }
}

/// The locales this port implements.
const PORTED: &[&str] = &["en", "th"];

/// Go: `localescompressed.GetTranslator(locale)`.
///
/// `Ok(None)` if Go does not know the locale (Go returns nil; callers fall back to the default
/// content language, then "en"). A locale Go knows but this port has no tables for is an explicit
/// `neohugo-rs: ... is not supported` error. Translators are created once and shared, like Go's
/// `translators` cache.
// Go: localescompressed locales.go:GetTranslator
pub fn get_translator(locale: &str) -> Result<Option<Arc<dyn Translator>>> {
    let locale = go_unicode::strings::to_lower(&go_unicode::strings::replace_all(
        locale.as_bytes(),
        b"-",
        b"_",
    ))
    .into_owned();

    if tables::LOCALE_NAMES
        .binary_search_by(|n| n.as_bytes().cmp(&locale))
        .is_err()
    {
        return Ok(None);
    }

    static EN: OnceLock<Arc<dyn Translator>> = OnceLock::new();
    static TH: OnceLock<Arc<dyn Translator>> = OnceLock::new();
    match &locale[..] {
        b"en" => Ok(Some(EN.get_or_init(|| Arc::new(tables::new_en())).clone())),
        b"th" => Ok(Some(TH.get_or_init(|| Arc::new(tables::new_th())).clone())),
        _ => Err(Error::new(format!(
            "neohugo-rs: locale {:?} is not supported (only {} are ported)",
            String::from_utf8_lossy(&locale),
            PORTED.join(", ")
        ))),
    }
}

/// Go: `localescompressed.GetCurrency(code)`: the `currency.Type` for the given ISO 4217 code
/// (case-insensitive), or -1 if not found.
// Go: localescompressed locales.go:GetCurrency
pub fn get_currency(code: &str) -> i64 {
    let code = go_unicode::strings::to_upper(code.as_bytes()).into_owned();
    match tables::CURRENCIES.binary_search_by(|(c, _)| c.as_bytes().cmp(&code)) {
        Ok(i) => tables::CURRENCIES[i].1,
        Err(_) => -1,
    }
}

