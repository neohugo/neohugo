// Go: internal/strconv/ftoa.go:ftoa32 / ftoa64 (identical bodies; Go keeps two
// manual specializations of one generic function only because of a compiler
// issue, go.dev/issue/79547).
fn ftoa(dst: &mut Vec<u8>, b: u64, fi: &FloatInfoF, fmt: u8, prec: i64) {
    let mut prec = prec;
    let exp_bits = fi.exp_bits;
    let mant_bits = fi.mant_bits;
    let bias = fi.bias;

    let neg = b >> (exp_bits + mant_bits) != 0;
    let mut exp = (b >> mant_bits) as i64 & ((1 << exp_bits) - 1);
    let mut mant = b & ((1u64 << mant_bits) - 1);
    if exp == (1 << exp_bits) - 1 {
        if mant != 0 {
            dst.extend_from_slice(b"NaN");
            return;
        }
        if neg {
            dst.extend_from_slice(b"-Inf");
            return;
        }
        dst.extend_from_slice(b"+Inf");
        return;
    }
    if exp == 0 {
        exp += 1;
    } else {
        mant |= 1u64 << mant_bits;
    }
    exp += bias;

    // Pick off easy binary, hex formats.
    if fmt == b'b' {
        return fmt_b(dst, neg, mant, exp - mant_bits);
    }
    if fmt == b'x' || fmt == b'X' {
        return fmt_x(dst, prec, fmt, neg, mant, exp, mant_bits);
    }

    // Pick off zero.
    if mant == 0 {
        return fmt_efg(dst, neg, &[], 0, 0, prec, fmt, prec < 0);
    }

    // Negative precision means "only as much as needed to be exact."
    if prec < 0 {
        // Use fast unrounded scaling.
        let mut buf = [0u8; 32];
        let s = 64 - len64(mant);
        let m = mant << s;
        let e = exp - s;
        let (d, p) = short_float(fi.short, m, e - mant_bits);
        let (dp, nd) = set_digits(&mut buf[..], d, p, num_digits(d));
        // Precision for shortest representation mode.
        match fmt {
            b'e' | b'E' => prec = (nd - 1).max(0),
            b'f' => prec = (nd - dp).max(0),
            b'g' | b'G' => prec = nd,
            _ => {}
        }
        return fmt_efg(dst, neg, &buf[..], dp, nd, prec, fmt, true);
    }

    if optimize() {
        // Fixed number of digits.
        let mut digits = prec;
        match fmt {
            b'f' => {
                // %f precision specifies digits after the decimal point.
                // Estimate an upper bound on the total number of digits needed.
                // ftoaFixed will shorten as needed according to prec.
                if exp >= 0 {
                    digits = (1 + log10_pow2(1 + exp)).wrapping_add(prec);
                } else {
                    digits = 1i64.wrapping_add(prec).wrapping_sub(log10_pow2(-exp));
                }
            }
            b'e' | b'E' => digits = digits.wrapping_add(1),
            b'g' | b'G' => {
                if prec == 0 {
                    prec = 1;
                }
                digits = prec;
            }
            _ => {
                // Invalid mode.
                digits = 1;
            }
        }
        if digits <= 18 {
            // digits <= 0 happens for %f on very small numbers
            // and means that we're guaranteed to print all zeros.
            let mut buf = [0u8; 24];
            let mut dp = 0;
            let mut nd = 0;
            if digits > 0 {
                let s = 64 - len64(mant);
                let m = mant << s;
                let e = exp - s;
                let (d, p) = fixed_width_float(m, e - mant_bits, digits, prec, fmt);
                if d != 0 {
                    (dp, nd) = set_digits(&mut buf[..], d, p, num_digits(d));
                }
            }
            return fmt_efg(dst, neg, &buf[..], dp, nd, prec, fmt, false);
        }
    }

    // Slow bignum case. Only for non-shortest results.
    let mut d = Box::<Decimal>::default();
    d.assign(mant);
    d.shift(exp - mant_bits);
    match fmt {
        b'e' | b'E' => d.round(prec.wrapping_add(1)),
        b'f' => {
            let nd = d.dp.wrapping_add(prec);
            d.round(nd)
        }
        b'g' | b'G' => {
            if prec == 0 {
                prec = 1;
            }
            d.round(prec);
        }
        _ => {}
    }
    fmt_efg(dst, neg, &d.d[..], d.dp, d.nd, prec, fmt, false)
}

// Go: internal/strconv/ftoa.go:fmtEFG
#[allow(clippy::too_many_arguments)]
fn fmt_efg(
    dst: &mut Vec<u8>,
    neg: bool,
    s: &[u8],
    dp: i64,
    nd: i64,
    prec: i64,
    fmt: u8,
    shortest: bool,
) {
    let mut prec = prec;
    let mut fmt = fmt;
    if fmt == b'g' || fmt == b'G' {
        // trailing fractional zeros in 'e' form will be trimmed.
        let mut eprec = prec;
        if eprec > nd && nd >= dp {
            eprec = nd;
        }
        // %e is used if the exponent from the conversion
        // is less than -4 or greater than or equal to the precision.
        // if precision was the shortest possible, use precision 6 for this decision.
        if shortest {
            eprec = 6;
        }
        let exp = dp - 1;
        if exp < -4 || exp >= eprec {
            if prec > nd {
                prec = nd;
            }
            prec -= 1;
            fmt = fmt.wrapping_add(b'e').wrapping_sub(b'g');
        } else {
            if prec > dp {
                prec = nd;
            }
            prec = (prec - dp).max(0);
            fmt = b'f';
        }
    }

    match fmt {
        b'e' | b'E' => {
            // %e: -d.ddddde±dd
            // sign
            if neg {
                dst.push(b'-');
            }

            // first digit
            let mut ch = b'0';
            if nd != 0 {
                ch = s[0];
            }
            dst.push(ch);

            // .moredigits
            if prec > 0 {
                dst.push(b'.');
                let mut i: i64 = 1;
                let m = nd.min(prec + 1);
                if i < m {
                    dst.extend_from_slice(&s[i as usize..m as usize]);
                    i = m;
                }
                for _ in 0..(prec + 1 - i) {
                    dst.push(b'0');
                }
            }

            // e±
            dst.push(fmt);
            let mut exp = dp - 1;
            if nd == 0 {
                // special case: 0 has exponent 0
                exp = 0;
            }
            if exp < 0 {
                ch = b'-';
                exp = -exp;
            } else {
                ch = b'+';
            }
            dst.push(ch);

            // dd or ddd
            if exp < 10 {
                dst.push(b'0');
                dst.push(exp as u8 + b'0');
            } else if exp < 100 {
                dst.push((exp / 10) as u8 + b'0');
                dst.push((exp % 10) as u8 + b'0');
            } else {
                dst.push((exp / 100) as u8 + b'0');
                dst.push(((exp / 10) as u8 % 10) + b'0');
                dst.push((exp % 10) as u8 + b'0');
            }
        }

        b'f' => {
            // %f: -ddddddd.ddddd
            // sign
            if neg {
                dst.push(b'-');
            }

            // integer, padded with zeros as needed.
            if dp > 0 {
                let m = nd.min(dp);
                dst.extend_from_slice(&s[..m as usize]);
                for _ in 0..(dp - m) {
                    dst.push(b'0');
                }
            } else {
                dst.push(b'0');
            }

            // fraction
            if prec > 0 {
                dst.push(b'.');
                let lz = prec.min(0i64.max(-dp)); // leading zeros
                let off = dp + lz;
                let m = (prec - lz).min(0i64.max(nd - off)); // middle digits
                let tz = 0i64.max(prec - lz - m); // trailing zeros
                for _ in 0..lz {
                    dst.push(b'0');
                }
                for i in 0..m {
                    dst.push(s[(off + i) as usize]);
                }
                for _ in 0..tz {
                    dst.push(b'0');
                }
            }
        }

        _ => {
            // unknown format
            dst.push(b'%');
            dst.push(fmt);
        }
    }
}

// Go: internal/strconv/ftoa.go:fmtB
/// %b: -ddddddddp±ddd
fn fmt_b(dst: &mut Vec<u8>, neg: bool, mant: u64, exp: i64) {
    if neg {
        dst.push(b'-');
    }
    append_uint(dst, mant, 10);
    dst.push(b'p');
    if exp >= 0 {
        dst.push(b'+');
    }
    append_int(dst, exp, 10);
}

// Go: internal/strconv/ftoa.go:fmtX
/// %x: -0x1.yyyyyyyyp±ddd or -0x0p+0. (y is hex digit, d is decimal digit)
fn fmt_x(dst: &mut Vec<u8>, prec: i64, fmt: u8, neg: bool, mant: u64, exp: i64, mant_bits: i64) {
    let mut mant = mant;
    let mut exp = exp;
    if mant == 0 {
        exp = 0;
    }

    // Shift digits so leading 1 (if any) is at bit 1<<60.
    mant <<= 60 - mant_bits;
    while mant != 0 && mant & (1 << 60) == 0 {
        mant <<= 1;
        exp -= 1;
    }

    // Round if requested.
    if (0..15).contains(&prec) {
        let shift = (prec * 4) as u32;
        let extra = (mant << shift) & ((1 << 60) - 1);
        mant >>= 60 - shift;
        if (extra | (mant & 1)) > (1 << 59) {
            mant += 1;
        }
        mant <<= 60 - shift;
        if mant & (1 << 61) != 0 {
            // Wrapped around.
            mant >>= 1;
            exp += 1;
        }
    }

    let hex = if fmt == b'X' { UPPERHEX } else { LOWERHEX };

    // sign, 0x, leading digit
    if neg {
        dst.push(b'-');
    }
    dst.push(b'0');
    dst.push(fmt);
    dst.push(b'0' + ((mant >> 60) & 1) as u8);

    // .fraction
    mant <<= 4; // remove leading 0 or 1
    if prec < 0 && mant != 0 {
        dst.push(b'.');
        while mant != 0 {
            dst.push(hex[((mant >> 60) & 15) as usize]);
            mant <<= 4;
        }
    } else if prec > 0 {
        dst.push(b'.');
        let mut i = 0;
        while i < prec {
            dst.push(hex[((mant >> 60) & 15) as usize]);
            mant <<= 4;
            i += 1;
        }
    }

    // p±
    let mut ch = b'P';
    if fmt == lower(fmt) {
        ch = b'p';
    }
    dst.push(ch);
    if exp < 0 {
        ch = b'-';
        exp = -exp;
    } else {
        ch = b'+';
    }
    dst.push(ch);

    // dd or ddd or dddd
    if exp < 100 {
        dst.push((exp / 10) as u8 + b'0');
        dst.push((exp % 10) as u8 + b'0');
    } else if exp < 1000 {
        dst.push((exp / 100) as u8 + b'0');
        dst.push(((exp / 10) % 10) as u8 + b'0');
        dst.push((exp % 10) as u8 + b'0');
    } else {
        dst.push((exp / 1000) as u8 + b'0');
        dst.push(((exp / 100) as u8 % 10) + b'0');
        dst.push(((exp / 10) % 10) as u8 + b'0');
        dst.push((exp % 10) as u8 + b'0');
    }
}

/// lower(c) is a lower-case letter if and only if
/// c is either that lower-case letter or the equivalent upper-case letter.
#[inline]
pub(crate) fn lower(c: u8) -> u8 {
    c | (b'x' - b'X')
}
