/// FormatFloat converts the floating-point number f to a string,
/// according to the format fmt and precision prec. It rounds the
/// result assuming that the original was obtained from a floating-point
/// value of bitSize bits (32 for float32, 64 for float64).
///
/// The format fmt is one of
///   - 'b' (-ddddp±ddd, a binary exponent),
///   - 'e' (-d.dddde±dd, a decimal exponent),
///   - 'E' (-d.ddddE±dd, a decimal exponent),
///   - 'f' (-ddd.dddd, no exponent),
///   - 'g' ('e' for large exponents, 'f' otherwise),
///   - 'G' ('E' for large exponents, 'f' otherwise),
///   - 'x' (-0xd.ddddp±ddd, a hexadecimal fraction and binary exponent), or
///   - 'X' (-0Xd.ddddP±ddd, a hexadecimal fraction and binary exponent).
///
/// The precision prec controls the number of digits (excluding the exponent)
/// printed by the 'e', 'E', 'f', 'g', 'G', 'x', and 'X' formats.
/// For 'e', 'E', 'f', 'x', and 'X', it is the number of digits after the decimal point.
/// For 'g' and 'G' it is the maximum number of significant digits (trailing
/// zeros are removed).
/// The special precision -1 uses the smallest number of digits
/// necessary such that ParseFloat will return f exactly.
///
/// Panics (like Go) if bitSize is not 32 or 64.
///
/// Deviation: for a finite value and a non-ASCII `fmt` byte (>= 0x80) Go
/// returns the invalid-UTF-8 string `"%" + fmt`, which a Rust `String`
/// cannot hold, so this panics instead; [`append_float`] returns Go's bytes.
pub fn format_float(f: f64, fmt: u8, prec: i64, bit_size: i64) -> String {
    let mut dst = Vec::with_capacity((prec.saturating_add(4)).clamp(24, 1 << 16) as usize);
    if bit_size == 32 {
        ftoa32(&mut dst, f64_to_f32(f), fmt, prec);
        return float_string(dst);
    }
    if bit_size == 64 {
        ftoa64(&mut dst, f, fmt, prec);
        return float_string(dst);
    }
    panic!("strconv: illegal FormatFloat bitSize");
}

/// Converts FormatFloat/FormatComplex output to a String. The output is
/// ASCII except for Go's `"%" + fmt` form with a non-ASCII fmt byte.
pub(crate) fn float_string(b: Vec<u8>) -> String {
    String::from_utf8(b).unwrap_or_else(|e| {
        panic!(
            "go_strconv: FormatFloat with non-ASCII fmt byte gives invalid UTF-8 {:?}; use append_float",
            e.as_bytes()
        )
    })
}

// Go: internal/strconv/ftoa.go:AppendFloat
/// AppendFloat appends the string form of the floating-point number f,
/// as generated by FormatFloat, to dst.
///
/// Panics (like Go) if bitSize is not 32 or 64.
pub fn append_float(dst: &mut Vec<u8>, f: f64, fmt: u8, prec: i64, bit_size: i64) {
    if bit_size == 32 {
        return ftoa32(dst, f64_to_f32(f), fmt, prec);
    }
    if bit_size == 64 {
        return ftoa64(dst, f, fmt, prec);
    }
    panic!("strconv: illegal AppendFloat bitSize");
}

/// The parameterized constants of Go's ftoa32/ftoa64 specializations.
struct FloatInfoF {
    exp_bits: i64,
    mant_bits: i64,
    bias: i64,
    short: FloatParams,
}

const F32: FloatInfoF = FloatInfoF {
    exp_bits: FLOAT32_EXP_BITS,
    mant_bits: FLOAT32_MANT_BITS,
    bias: FLOAT32_BIAS,
    short: SHORT_F32,
};

const F64: FloatInfoF = FloatInfoF {
    exp_bits: FLOAT64_EXP_BITS,
    mant_bits: FLOAT64_MANT_BITS,
    bias: FLOAT64_BIAS,
    short: SHORT_F64,
};

